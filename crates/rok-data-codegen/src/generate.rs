//! Turn the `.sql` files into the generated crate's files.

use std::collections::{BTreeMap, BTreeSet};
use std::fs;
use std::path::{Path, PathBuf};

use crate::ddl::Rename;
use crate::describe::{self, Cache};
use crate::emit;
use crate::ir::Schema;
use crate::parse::{self, SourceFile};
use crate::queries;
use crate::truth::{self, MigrationFile};
use crate::types::Feature;
use crate::{Error, naming};

/// Where rok-data comes from in the generated `Cargo.toml`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Dependency {
    /// `rok-data = { version = "..." }`.
    Version(String),
    /// `rok-data = { path = "..." }`, relative to the project root.
    Path(PathBuf),
}

/// What to generate, and how.
#[derive(Debug, Clone)]
pub struct Options {
    /// Directory holding the `.sql` files.
    pub input: PathBuf,
    /// Directory of the generated crate.
    pub output: PathBuf,
    /// Package name of the generated crate.
    pub crate_name: String,
    /// The rok-data dependency of the generated crate.
    pub rok_data: Dependency,
    /// Treat warnings (queries that skip tenant or soft-delete filters) as errors.
    pub strict: bool,
    /// PostgreSQL server for checking queries that aren't in `queries.json`.
    pub database_url: Option<String>,
    /// Name for a new migration, when the schema changed.
    pub migration: Option<String>,
    /// Renames to apply instead of drop-and-add.
    pub renames: Vec<Rename>,
    /// Allow steps that can lose data or fail on existing rows.
    pub allow_destructive: bool,
}

impl Options {
    /// Defaults: `db/` to `db-gen/`, rok-data from crates.io.
    pub fn new() -> Self {
        Self {
            input: PathBuf::from("db"),
            output: PathBuf::from("db-gen"),
            crate_name: "db-gen".to_owned(),
            rok_data: Dependency::Version(default_version()),
            strict: false,
            database_url: None,
            migration: None,
            renames: Vec::new(),
            allow_destructive: false,
        }
    }
}

/// `0.4` for rok-data-codegen 0.4.x: the matching rok-data release.
fn default_version() -> String {
    env!("CARGO_PKG_VERSION")
        .splitn(3, '.')
        .take(2)
        .collect::<Vec<_>>()
        .join(".")
}

impl Default for Options {
    fn default() -> Self {
        Self::new()
    }
}

/// The generated files, relative to the output directory.
#[derive(Debug, Default)]
pub struct Generated {
    /// Files to write.
    pub files: BTreeMap<PathBuf, String>,
    /// Previously generated files that are no longer produced.
    pub stale: Vec<PathBuf>,
    /// The migration this run adds, if any.
    pub new_migration: Option<String>,
    /// Warnings to show.
    pub warnings: Vec<String>,
}

const HEADER: &str =
    "// @generated by rok. Do not edit: change the .sql files and run `rok generate`.";

/// Generate everything in memory. Nothing is written.
pub fn generate(options: &Options) -> Result<Generated, Error> {
    let sources = truth::read_sources(&options.input)?;
    let parsed = parse::parse(&sources)?;
    let output = &options.output;
    let mut generated = Generated::default();

    // Migrations: compare with the snapshot of the latest one.
    let snapshot_path = output.join("schema.json");
    let snapshot: Schema = match fs::read_to_string(&snapshot_path) {
        Ok(text) => serde_json::from_str(&text)
            .map_err(|e| Error::new(format!("{}: {e}", snapshot_path.display())))?,
        Err(_) => Schema::default(),
    };
    let mut migrations = truth::existing_migrations(&output.join("migrations"))?;
    if migrations.is_empty() && snapshot != Schema::default() {
        return Err(Error::new(format!(
            "{} exists but {} has no migrations; restore them or delete the snapshot",
            snapshot_path.display(),
            output.join("migrations").display()
        )));
    }
    let pair = truth::migration(&snapshot, &parsed.schema, &options.renames)?;
    let name = match (&options.migration, pair.is_empty()) {
        (Some(_), true) if options.renames.is_empty() => {
            return Err(Error::nothing_to_migrate());
        }
        (Some(name), _) => Some(naming::snake_ident(name)),
        (None, false) if migrations.is_empty() => Some("init".to_owned()),
        (None, false) => {
            let preview: Vec<String> = pair
                .steps
                .iter()
                .take(5)
                .map(|line| format!("  {line}"))
                .collect();
            return Err(Error::new(format!(
                "the .sql files changed since the last migration:\n{}{}\nrun `rok generate --migration <name>` to add a migration",
                preview.join("\n"),
                if pair.steps.len() > 5 { "\n  ..." } else { "" }
            )));
        }
        (None, true) => None,
    };
    if let Some(name) = name {
        if !pair.destructive.is_empty() && !options.allow_destructive {
            return Err(Error::new(format!(
                "migration `{name}` would:\n  - {}\nre-run with --allow-destructive if that is intended, or use --rename for renames",
                pair.destructive.join("\n  - ")
            )));
        }
        let version = migrations.last().map_or(1, |m| m.version + 1);
        let up = pair.up;
        let down = pair.down;
        let stem = format!("{version:04}_{name}");
        generated.files.insert(
            PathBuf::from(format!("migrations/{stem}.up.sql")),
            up.clone(),
        );
        if !down.is_empty() {
            generated.files.insert(
                PathBuf::from(format!("migrations/{stem}.down.sql")),
                down.clone(),
            );
        } else {
            generated.warnings.push(format!(
                "migration `{stem}` can't be reverted automatically (it adds enum values or removes statements without down SQL)"
            ));
        }
        migrations.push(MigrationFile {
            version,
            name: name.clone(),
            stem,
            up,
            reversible: !down.is_empty(),
        });
        generated.new_migration = Some(name);
    }
    generated
        .files
        .insert(PathBuf::from("schema.json"), json(&parsed.schema)?);

    // Queries: types from PostgreSQL (or the cache).
    let cache_path = output.join("queries.json");
    let cache: Cache = match fs::read_to_string(&cache_path) {
        Ok(text) => serde_json::from_str(&text).unwrap_or_default(),
        Err(_) => Cache::default(),
    };
    let up_scripts: Vec<String> = migrations.iter().map(|m| m.up.clone()).collect();
    // The database word (workspace ADR 0010): the parse is offline and first, but with
    // a URL at hand the migrations are applied to a temporary database and
    // the catalog is compared with `parsed.schema`; without one, the run
    // stays parser-only.
    if let Some(url) = options.database_url.as_deref() {
        let drift = describe::verify_schema(&parsed.schema, &up_scripts, url)?;
        if !drift.is_empty() {
            if options.strict {
                return Err(Error::new(format!("--strict: {}", drift.join("\n"))));
            }
            generated.warnings.extend(drift);
        }
    }
    let (descriptions, cache) = describe::describe_all(
        &parsed.queries,
        &up_scripts,
        &cache,
        options.database_url.as_deref(),
    )?;
    generated
        .files
        .insert(PathBuf::from("queries.json"), json(&cache)?);

    // Rust.
    let mut features = BTreeSet::new();
    let mut modules = emit::models(&parsed.schema, &mut features)?;
    let mut warnings = Vec::new();
    let all_modules: BTreeSet<String> = parsed
        .modules
        .iter()
        .chain(modules.keys())
        .cloned()
        .collect();
    for module in &all_modules {
        let mine: Vec<_> = parsed
            .queries
            .iter()
            .zip(&descriptions)
            .filter(|(q, _)| &q.module == module)
            .collect();
        let code = queries::functions(&mine, &parsed.schema, &mut features, &mut warnings)?;
        modules.entry(module.clone()).or_default().push_str(&code);
    }
    if options.strict && !warnings.is_empty() {
        return Err(Error::new(format!("--strict: {}", warnings.join("\n"))));
    }
    generated.warnings.extend(warnings);

    let input_display = options.input.file_name().map_or_else(
        || options.input.display().to_string(),
        |n| n.to_string_lossy().into_owned(),
    );
    for (module, code) in &modules {
        let source = parsed_source(&sources, module);
        let doc = format!("//! Generated from `{source}`.\n\n{code}");
        generated.files.insert(
            PathBuf::from(format!("src/{module}.rs")),
            emit::format(&doc, HEADER)?,
        );
    }
    generated.files.insert(
        PathBuf::from("src/lib.rs"),
        lib_rs(&modules, &input_display)?,
    );
    generated.files.insert(
        PathBuf::from("src/migrations.rs"),
        migrations_rs(&migrations)?,
    );
    generated
        .files
        .insert(PathBuf::from("src/up.rs"), emit::format(UP_RS, HEADER)?);
    generated
        .files
        .insert(PathBuf::from("src/down.rs"), emit::format(DOWN_RS, HEADER)?);
    generated
        .files
        .insert(PathBuf::from("Cargo.toml"), cargo_toml(options, &features));

    // Generated sources that are no longer produced (a removed .sql file).
    if let Ok(entries) = fs::read_dir(output.join("src")) {
        for entry in entries.flatten() {
            let rel = PathBuf::from("src").join(entry.file_name());
            let is_generated = fs::read_to_string(entry.path())
                .is_ok_and(|t| t.starts_with("// @generated by rok"));
            if is_generated && !generated.files.contains_key(&rel) {
                generated.stale.push(rel);
            }
        }
    }
    Ok(generated)
}

/// Write the files that changed and remove stale ones. Returns the paths
/// written.
pub fn write(options: &Options, generated: &Generated) -> Result<Vec<PathBuf>, Error> {
    let io = |path: &Path, e: std::io::Error| Error::new(format!("{}: {e}", path.display()));
    let mut written = Vec::new();
    for (rel, content) in &generated.files {
        let path = options.output.join(rel);
        if fs::read_to_string(&path).is_ok_and(|old| &old == content) {
            continue;
        }
        if let Some(dir) = path.parent() {
            fs::create_dir_all(dir).map_err(|e| io(dir, e))?;
        }
        fs::write(&path, content).map_err(|e| io(&path, e))?;
        written.push(rel.clone());
    }
    for rel in &generated.stale {
        let path = options.output.join(rel);
        fs::remove_file(&path).map_err(|e| io(&path, e))?;
        written.push(rel.clone());
    }
    Ok(written)
}

/// Files whose content on disk differs from `generated` (CI check).
pub fn differences(options: &Options, generated: &Generated) -> Vec<PathBuf> {
    let mut out: Vec<PathBuf> = generated
        .files
        .iter()
        .filter(|(rel, content)| {
            fs::read_to_string(options.output.join(rel)).map_or(true, |old| &old != *content)
        })
        .map(|(rel, _)| rel.clone())
        .collect();
    out.extend(generated.stale.iter().cloned());
    out
}

fn parsed_source(sources: &[SourceFile], module: &str) -> String {
    let paths: Vec<&str> = sources
        .iter()
        .filter(|s| s.module == module || (module == "types" && s.module.starts_with('_')))
        .map(|s| s.path.as_str())
        .collect();
    paths.join("`, `")
}

/// Resolve `.` and `..` without touching the file system.
fn normalize(path: &Path) -> PathBuf {
    let mut out = PathBuf::new();
    for component in path.components() {
        match component {
            std::path::Component::CurDir => {}
            std::path::Component::ParentDir => {
                if matches!(
                    out.components().next_back(),
                    Some(std::path::Component::Normal(_))
                ) {
                    out.pop();
                } else {
                    out.push("..");
                }
            }
            other => out.push(other),
        }
    }
    out
}

/// `to` relative to the directory `from` (both relative to the same place,
/// or both absolute).
fn relative_path(from: &Path, to: &Path) -> PathBuf {
    let from = normalize(from);
    let to = normalize(to);
    let from: Vec<_> = from.components().collect();
    let to: Vec<_> = to.components().collect();
    let common = from.iter().zip(&to).take_while(|(a, b)| a == b).count();
    let mut out = PathBuf::new();
    for _ in common..from.len() {
        out.push("..");
    }
    for c in &to[common..] {
        out.push(c);
    }
    out
}

/// A value as the generator's JSON files hold it: pretty, with a trailing
/// newline.
pub(crate) fn json<T: serde::Serialize>(value: &T) -> Result<String, Error> {
    serde_json::to_string_pretty(value)
        .map(|s| s + "\n")
        .map_err(|e| Error::new(e.to_string()))
}

fn lib_rs(modules: &BTreeMap<String, String>, input: &str) -> Result<String, Error> {
    // `#[rustfmt::skip]` keeps `cargo fmt` from reformatting generated
    // modules (which would make `rok check` fail); declarations are
    // sorted the way rustfmt sorts them.
    let mut mods: Vec<(String, &str)> = modules.keys().map(|m| (m.clone(), "pub ")).collect();
    mods.push(("migrations".to_owned(), "pub "));
    mods.push(("down".to_owned(), ""));
    mods.push(("up".to_owned(), ""));
    mods.sort();
    let mods: String = mods
        .iter()
        .map(|(m, vis)| format!("#[rustfmt::skip]\n{vis}mod {m};\n"))
        .collect();
    let source = format!(
        "//! Database code generated by rok from `{input}/*.sql`: one module\n\
         //! per file with its models, enums and queries, and the migrations.\n\
         //!\n\
         //! Apply pending migrations with [`up`] and revert them with [`down`].\n\
         #![allow(clippy::all, clippy::pedantic, clippy::nursery)]\n\n\
         {mods}\n\
         pub use down::down;\n\
         pub use up::up;\n"
    );
    emit::format(&source, HEADER)
}

fn migrations_rs(migrations: &[MigrationFile]) -> Result<String, Error> {
    let mut items = String::new();
    for m in migrations {
        let down = if m.reversible {
            format!("include_str!(\"../migrations/{}.down.sql\")", m.stem)
        } else {
            "\"\"".to_owned()
        };
        items.push_str(&format!(
            "rok_data::migration::Migration {{ version: {}, name: {:?}, up: include_str!(\"../migrations/{}.up.sql\"), down: {down} }},\n",
            m.version, m.name, m.stem
        ));
    }
    let source = format!(
        "//! Every migration, oldest first. Each one is a pair of files in\n\
         //! `migrations/`; never edit a migration that was applied somewhere.\n\n\
         /// Every migration, oldest first.\n\
         pub const MIGRATIONS: &[rok_data::migration::Migration] = &[\n{items}];\n"
    );
    emit::format(&source, HEADER)
}

const UP_RS: &str = "/// Apply every pending migration, oldest first, each in its own transaction.\n\
/// Returns the versions applied.\n\
pub async fn up(db: &rok_data::Db) -> rok_data::Result<Vec<i64>> {\n\
    rok_data::migration::apply(db, crate::migrations::MIGRATIONS).await\n\
}\n";

const DOWN_RS: &str = "/// Revert the latest `steps` applied migrations, newest first. Returns the\n\
/// versions reverted.\n\
pub async fn down(db: &rok_data::Db, steps: usize) -> rok_data::Result<Vec<i64>> {\n\
    rok_data::migration::revert(db, crate::migrations::MIGRATIONS, steps).await\n\
}\n";

fn cargo_toml(options: &Options, features: &BTreeSet<Feature>) -> String {
    let features: Vec<String> = features.iter().map(|f| format!("{:?}", f.name())).collect();
    let features = if features.is_empty() {
        String::new()
    } else {
        format!(", features = [{}]", features.join(", "))
    };
    let source = match &options.rok_data {
        Dependency::Version(v) => format!("version = {v:?}"),
        Dependency::Path(p) => {
            let relative = relative_path(&options.output, p);
            format!(
                "path = {:?}, version = {:?}",
                relative.display().to_string().replace('\\', "/"),
                default_version()
            )
        }
    };
    format!(
        "# @generated by rok. Do not edit: settings live in rok.toml.\n\
         [package]\n\
         name = {:?}\n\
         version = \"0.1.0\"\n\
         edition = \"2024\"\n\
         publish = false\n\
         description = \"Database models, queries and migrations generated by rok\"\n\n\
         [dependencies]\n\
         rok-data = {{ {source}{features} }}\n",
        options.crate_name
    )
}
