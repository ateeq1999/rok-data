//! Helpers shared by the `sqlc` CLI suites, adapted for rok-cli: fixtures
//! stay with the `rok-data-sqlc` engine they exercise, one directory up.
#![allow(dead_code)]

use std::path::{Path, PathBuf};
use std::process::Command;

use anyhow::{Context, Result, ensure};

/// The rok-data-sqlc engine crate's root (the fixtures live there).
pub(crate) fn sqlc_manifest_dir() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("..")
        .join("rok-data-sqlc")
        .canonicalize()
        .expect("the rok-data-sqlc crate is next to rok-cli")
}

/// The template directory `dir` (such as `axum-api`) of the rok-templates
/// crate, which `rok sqlc init --template` copies (workspace ADR 0022).
pub(crate) fn template_dir(dir: &str) -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("..")
        .join("rok-templates")
        .join("templates")
        .join(dir)
        .canonicalize()
        .expect("the rok-templates crate is next to rok-cli")
}

/// The rok-data-sqlc crate's root, for code that still calls it that way.
pub(crate) fn manifest_dir() -> PathBuf {
    sqlc_manifest_dir()
}

/// The fixture crate `tests/<name>`, e.g. `fixture-app`.
pub(crate) fn app_dir(name: &str) -> PathBuf {
    sqlc_manifest_dir().join("tests").join(name)
}

/// `cargo <args>` in the crate at `dir`. Every crate that compiles generated
/// code builds into one shared target directory, so its dependencies are
/// built once.
///
/// Incremental compilation is off: several gates build in that directory
/// at once, and an interrupted or concurrent build can leave a corrupt
/// incremental cache whose `warning:` fails a gate that demands a clean
/// build. These one-shot builds gain nothing from the cache anyway.
pub(crate) fn cargo(dir: &Path, args: &[&str]) -> Command {
    let mut command = Command::new("cargo");
    command
        .args(args)
        .current_dir(dir)
        .env(
            "CARGO_TARGET_DIR",
            PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("target/fixture-target"),
        )
        .env("CARGO_INCREMENTAL", "0");
    command
}

/// A path the way `rok sqlc` prints one outside the current directory: `/`
/// as the separator on every platform.
pub(crate) fn shown(path: &Path) -> String {
    path.display().to_string().replace('\\', "/")
}

/// Generated code targets SQLx 0.9, whose minimum Rust version is above the
/// tool's own. Returns why a suite that builds a fixture crate must skip on
/// the current toolchain, or `None` when the toolchain meets the floor the
/// fixture crate declares in its `rust-version`.
pub(crate) fn generated_code_skip_reason(fixture: &Path) -> Option<String> {
    let manifest: toml::Table = std::fs::read_to_string(fixture.join("Cargo.toml"))
        .expect("read the fixture crate's Cargo.toml")
        .parse()
        .expect("parse the fixture crate's Cargo.toml");
    let floor = manifest["package"]["rust-version"]
        .as_str()
        .expect("the fixture crate declares package.rust-version")
        .to_owned();
    let rustc = std::env::var("RUSTC").unwrap_or_else(|_| "rustc".into());
    let output = Command::new(rustc)
        .arg("--version")
        .output()
        .expect("run rustc --version");
    let version = String::from_utf8_lossy(&output.stdout);
    // "rustc 1.94.0 (...)"
    let current = version
        .split_whitespace()
        .nth(1)
        .expect("rustc --version prints a version")
        .to_owned();
    let (major, minor, patch) = parse(&current);
    let (fmajor, fminor, fpatch) = parse(&floor);
    if (major, minor, patch) >= (fmajor, fminor, fpatch) {
        None
    } else {
        Some(format!(
            "this fixture crate needs rustc {floor}; the toolchain is {current}"
        ))
    }
}

fn parse(version: &str) -> (u32, u32, u32) {
    let parts: Vec<u32> = version
        .trim_end_matches(|c: char| !c.is_ascii_digit())
        .split('.')
        .filter_map(|p| p.parse().ok())
        .collect();
    (
        *parts.first().unwrap_or(&0),
        *parts.get(1).unwrap_or(&0),
        *parts.get(2).unwrap_or(&0),
    )
}

/// Whether `text` looks like a generated file (first line carries the
/// generated marker of either the consolidated or the legacy generator).
pub(crate) fn is_generated(text: &str) -> bool {
    let first = text.lines().next().unwrap_or("");
    first.contains("@generated by rok-data-sqlc") || first.contains("@generated by rok-sqlc")
}

/// `rok gen <args>` in `dir`, which must succeed, and returns its stderr.
pub(crate) fn rok_gen(dir: &Path, args: &[&str]) -> Result<String> {
    let output = Command::new(env!("CARGO_BIN_EXE_rok"))
        .arg("gen")
        .args(args)
        .current_dir(dir)
        .output()
        .context("failed to run rok gen")?;
    let stderr = String::from_utf8_lossy(&output.stderr).into_owned();
    ensure!(
        output.status.success(),
        "rok gen {args:?} failed:\n{}{stderr}",
        String::from_utf8_lossy(&output.stdout),
    );
    Ok(stderr)
}

/// The workspace's `rok-data` crate, by absolute path (the release publishes
/// it afterwards; tests substitute it for the crates.io package).
pub(crate) fn workspace_rok_data_dir() -> PathBuf {
    let mut dir = std::env::current_dir().expect("run from a directory");
    loop {
        if dir.join("crates/rok-data/Cargo.toml").is_file() {
            return dir.join("crates/rok-data");
        }
        let parent = dir
            .parent()
            .expect("run inside the rok-data workspace")
            .to_owned();
        dir = parent;
    }
}

/// Redirects `rok-data` from the crates.io package to the workspace crate
/// while the tests run, as the release does first.
pub(crate) fn rok_data_patch_shim(dir: &Path) -> std::io::Result<()> {
    // TOML basic strings escape backslashes; forward slashes work everywhere.
    let workspace = workspace_rok_data_dir()
        .to_string_lossy()
        .replace('\\', "/");
    let replacements = format!("[patch.crates-io]\nrok-data = {{ path = \"{workspace}\" }}\n");
    let config = dir.join(".cargo/config.toml");
    std::fs::create_dir_all(config.parent().expect("a parent"))?;
    std::fs::write(&config, replacements)?;
    Ok(())
}
