//! `rok gen` and `rok gen check` in a monorepo whose `rok.toml` names
//! Clients (workspace ADR 0027): the clients are emitted from the
//! contract after the Apps, a contract change changes them, and the
//! check reports a client out of date — missing, changed or stale files —
//! without writing. A hand-owned file (its marker gone) is refused, and a
//! contract outside the subset fails naming the construct.

use std::fs;
use std::path::Path;
use std::process::{Command, Output};

use anyhow::Result;
use serde_json::{Value, json};
use tempfile::TempDir;

fn rok(dir: &Path, args: &[&str]) -> Result<Output> {
    Ok(Command::new(env!("CARGO_BIN_EXE_rok"))
        .current_dir(dir)
        .args(args)
        .output()?)
}

fn text(bytes: &[u8]) -> String {
    String::from_utf8_lossy(bytes).into_owned()
}

fn assert_success(output: &Output) {
    assert!(
        output.status.success(),
        "stdout: {}\nstderr: {}",
        text(&output.stdout),
        text(&output.stderr)
    );
}

/// A contract with one operation, `GET /things`, answering a `Thing`;
/// `extra` adds properties to `Thing`.
fn contract(extra: Value) -> String {
    let mut properties = json!({"id": {"type": "string"}});
    if let (Some(base), Some(extra)) = (properties.as_object_mut(), extra.as_object()) {
        base.extend(extra.clone());
    }
    serde_json::to_string_pretty(&json!({
        "openapi": "3.1.0",
        "info": {"title": "api", "version": "1"},
        "paths": {"/things": {"get": {
            "tags": ["things"],
            "operationId": "list",
            "responses": {"200": {"description": "ok", "content": {"application/json": {
                "schema": {"$ref": "#/components/schemas/Thing"}
            }}}},
        }}},
        "components": {"schemas": {"Thing": {
            "type": "object", "required": ["id"], "properties": properties,
        }}},
    }))
    .unwrap_or_default()
}

/// A monorepo naming no Apps, its contract `openapi.json` and its TS
/// client in `clients/ts`; `export` is the contract's export command.
fn monorepo(export: Option<&str>) -> Result<TempDir> {
    let dir = TempDir::new()?;
    let export = export.map_or_else(String::new, |command| format!("export = {command}\n"));
    fs::write(
        dir.path().join("rok.toml"),
        format!(
            "[apps]\n\n[contract]\ndocument = \"openapi.json\"\n{export}\n[clients]\nts = \"clients/ts\"\n"
        ),
    )?;
    fs::write(dir.path().join("openapi.json"), contract(json!({})))?;
    Ok(dir)
}

#[test]
fn gen_emits_the_client_and_a_contract_change_flows_through_check() -> Result<()> {
    let project = monorepo(None)?;
    let dir = project.path();

    let output = rok(dir, &["gen"])?;
    assert_success(&output);
    let stdout = text(&output.stdout);
    assert!(stdout.contains("clients:\n"), "{stdout}");
    assert!(
        stdout.contains("generated clients/ts/src/types.ts"),
        "{stdout}"
    );
    let types = fs::read_to_string(dir.join("clients/ts/src/types.ts"))?;
    assert!(
        types.starts_with("// @generated by rok-data-sqlc"),
        "{types}"
    );
    assert!(
        types.contains("export type Thing = {\n  id: string\n}\n"),
        "{types}"
    );
    assert_success(&rok(dir, &["gen", "check"])?);

    // A run over an up-to-date client writes nothing.
    let again = text(&rok(dir, &["gen"])?.stdout);
    assert!(
        again.contains("unchanged clients/ts/src/types.ts"),
        "{again}"
    );

    // The contract grows a property: the check fails, naming the client
    // and the changed file, and writes nothing.
    fs::write(
        dir.join("openapi.json"),
        contract(json!({"name": {"type": ["string", "null"]}})),
    )?;
    let check = rok(dir, &["gen", "check"])?;
    assert!(!check.status.success());
    assert!(text(&check.stdout).contains("changed clients/ts/src/types.ts"));
    assert!(
        text(&check.stderr).contains(
            "error: the `ts` client is out of date with openapi.json; run `rok gen` to update it"
        ),
        "{}",
        text(&check.stderr)
    );
    assert_eq!(
        fs::read_to_string(dir.join("clients/ts/src/types.ts"))?,
        types
    );

    // `rok gen` brings it up to date.
    assert_success(&rok(dir, &["gen"])?);
    let types = fs::read_to_string(dir.join("clients/ts/src/types.ts"))?;
    assert!(types.contains("  name?: string | null\n"), "{types}");
    assert_success(&rok(dir, &["gen", "check"])?);
    Ok(())
}

#[test]
fn a_file_no_longer_emitted_is_stale_and_removed() -> Result<()> {
    let project = monorepo(None)?;
    let dir = project.path();
    assert_success(&rok(dir, &["gen"])?);
    let old = dir.join("clients/ts/src/old.ts");
    fs::write(
        &old,
        "// @generated by rok-data-sqlc from openapi.json. Do not edit by hand.\n",
    )?;
    let check = rok(dir, &["gen", "check"])?;
    assert!(!check.status.success());
    assert!(text(&check.stdout).contains("stale clients/ts/src/old.ts"));

    let output = rok(dir, &["gen"])?;
    assert_success(&output);
    assert!(text(&output.stdout).contains("removed clients/ts/src/old.ts"));
    assert!(!old.exists());
    // A file of the user's own, without the marker, is never stale.
    fs::write(
        dir.join("clients/ts/src/mine.ts"),
        "export const mine = 1\n",
    )?;
    assert_success(&rok(dir, &["gen", "check"])?);
    Ok(())
}

#[test]
fn a_hand_owned_client_file_is_refused_without_force() -> Result<()> {
    let project = monorepo(None)?;
    let dir = project.path();
    assert_success(&rok(dir, &["gen"])?);
    let calls = dir.join("clients/ts/src/calls.ts");
    fs::write(&calls, "export const api = {}\n")?;
    fs::write(
        dir.join("openapi.json"),
        contract(json!({"n": {"type": "integer"}})),
    )?;
    let output = rok(dir, &["gen"])?;
    assert!(!output.status.success());
    assert!(
        text(&output.stderr).contains("the `ts` client was not written"),
        "{}",
        text(&output.stderr)
    );
    assert_eq!(fs::read_to_string(&calls)?, "export const api = {}\n");
    assert_success(&rok(dir, &["gen", "--force"])?);
    assert!(fs::read_to_string(&calls)?.starts_with("// @generated by rok-data-sqlc"));
    Ok(())
}

#[test]
fn json_reports_carry_a_body_per_client() -> Result<()> {
    let project = monorepo(None)?;
    let dir = project.path();
    let output = rok(dir, &["gen", "--json"])?;
    assert_success(&output);
    let bodies: Value = serde_json::from_slice(&output.stdout)?;
    let client = bodies
        .as_array()
        .and_then(|bodies| bodies.iter().find(|body| body["client"] == "ts"))
        .cloned()
        .unwrap_or_default();
    assert_eq!(client["dir"], "clients/ts");
    assert_eq!(client["drift"], false);
    assert!(
        client["written"]
            .as_array()
            .is_some_and(|written| written.iter().any(|path| path == "clients/ts/src/calls.ts")),
        "{client}"
    );
    Ok(())
}

#[test]
fn a_contract_outside_the_subset_fails_naming_the_construct() -> Result<()> {
    let project = monorepo(None)?;
    let dir = project.path();
    let mut document: Value = serde_json::from_str(&contract(json!({})))?;
    document["paths"]["/things"]["get"]["parameters"] =
        json!([{"name": "X-Trace", "in": "header", "schema": {"type": "string"}}]);
    fs::write(dir.join("openapi.json"), document.to_string())?;
    let output = rok(dir, &["gen"])?;
    assert!(!output.status.success());
    let stderr = text(&output.stderr);
    assert!(
        stderr.contains("#/paths/~1things/get/parameters/0: a parameter in `header`"),
        "{stderr}"
    );
    assert!(!dir.join("clients/ts").exists());
    Ok(())
}

/// The export command runs before the clients are emitted; one that fails
/// stops the run and says which command it was.
#[test]
fn a_failing_export_stops_the_run_naming_the_command() -> Result<()> {
    let project = monorepo(Some("[\"rok-no-such-exporter\", \"--out\"]"))?;
    let output = rok(project.path(), &["gen"])?;
    assert!(!output.status.success());
    let stderr = text(&output.stderr);
    assert!(
        stderr.contains("re-exporting the contract: `rok-no-such-exporter --out` did not start"),
        "{stderr}"
    );
    // A dry run neither exports nor writes.
    let dry = rok(project.path(), &["gen", "--dry-run"])?;
    assert_success(&dry);
    assert!(text(&dry.stdout).contains("would write clients/ts/src/calls.ts"));
    assert!(!project.path().join("clients/ts").exists());
    Ok(())
}

/// `rok init --template monorepo` emits `clients/ts` from the contract it
/// scaffolds: the same files the template checks in as `rok gen`'s.
#[test]
fn init_emits_the_ts_client_from_the_scaffolded_contract() -> Result<()> {
    let project = TempDir::new()?;
    let output = rok(project.path(), &["init", "--template", "monorepo", "app"])?;
    assert_success(&output);
    let template = Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../rok-templates/templates/monorepo/clients/ts");
    for file in [
        "README.md",
        "src/calls.ts",
        "src/index.ts",
        "src/queries.ts",
        "src/runtime.ts",
        "src/types.ts",
    ] {
        let scaffolded = fs::read_to_string(project.path().join("app/clients/ts").join(file))?;
        let checked_in = fs::read_to_string(template.join(file))?.replace("\r\n", "\n");
        assert!(
            scaffolded == checked_in,
            "the scaffolded clients/ts/{file} is not the template's"
        );
    }
    Ok(())
}
