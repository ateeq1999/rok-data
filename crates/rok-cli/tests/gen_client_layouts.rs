//! `[clients]` entries as tables: `{ dir = "…", layout = "sources" }` emits
//! a Client's source files flat in an App's own directory (workspace ADR
//! 0027, amended 2026-11-03).

use std::fs;
use std::path::Path;
use std::process::{Command, Output};

use anyhow::Result;
use tempfile::TempDir;

const MARKER: &str = "// @generated by rok-data-sqlc from openapi.json. Do not edit by hand.\n";

/// One operation, `GET /things`, answering a `Thing`.
const CONTRACT: &str = r##"{
  "openapi": "3.1.0",
  "info": {"title": "api", "version": "1"},
  "paths": {"/things": {"get": {
    "tags": ["things"],
    "operationId": "list",
    "responses": {"200": {"description": "ok", "content": {"application/json": {
      "schema": {"$ref": "#/components/schemas/Thing"}
    }}}}
  }}},
  "components": {"schemas": {"Thing": {
    "type": "object", "required": ["id"], "properties": {"id": {"type": "string"}}
  }}}
}"##;

fn rok(dir: &Path, args: &[&str]) -> Result<Output> {
    Ok(Command::new(env!("CARGO_BIN_EXE_rok-data"))
        .current_dir(dir)
        .args(args)
        .output()?)
}

fn text(bytes: &[u8]) -> String {
    String::from_utf8_lossy(bytes).into_owned()
}

fn assert_success(output: &Output) {
    assert!(
        output.status.success(),
        "stdout: {}\nstderr: {}",
        text(&output.stdout),
        text(&output.stderr)
    );
}

/// A monorepo whose `[clients]` section is `clients`.
fn monorepo(clients: &str) -> Result<TempDir> {
    let dir = TempDir::new()?;
    fs::write(
        dir.path().join("rok.toml"),
        format!("[apps]\n\n[contract]\ndocument = \"openapi.json\"\n\n[clients]\n{clients}"),
    )?;
    fs::write(dir.path().join("openapi.json"), CONTRACT)?;
    Ok(dir)
}

/// The names of the files directly in `dir`, sorted; directories end in `/`.
fn listing(dir: &Path) -> Result<Vec<String>> {
    let mut names: Vec<String> = fs::read_dir(dir)?
        .map(|entry| {
            let entry = entry?;
            let mut name = entry.file_name().to_string_lossy().into_owned();
            if entry.path().is_dir() {
                name.push('/');
            }
            Ok(name)
        })
        .collect::<Result<_>>()?;
    names.sort();
    Ok(names)
}

#[test]
fn the_ts_client_as_sources_is_its_source_files_flat() -> Result<()> {
    let project = monorepo("ts = { dir = \"apps/web/src/lib/api\", layout = \"sources\" }\n")?;
    let dir = project.path();
    let api = dir.join("apps/web/src/lib/api");
    assert_success(&rok(dir, &["gen"])?);
    assert_eq!(
        listing(&api)?,
        [
            "calls.ts",
            "index.ts",
            "queries.ts",
            "runtime.ts",
            "types.ts"
        ]
    );
    let index = fs::read_to_string(api.join("index.ts"))?;
    assert!(index.starts_with(MARKER), "{index}");
    assert!(index.contains("export * from \"./runtime\"\n"), "{index}");
    let types = fs::read_to_string(api.join("types.ts"))?;
    assert!(types.contains("Thing"), "{types}");
    assert_success(&rok(dir, &["gen", "check"])?);
    Ok(())
}

#[test]
fn the_dart_client_as_sources_has_an_export_file_and_no_package() -> Result<()> {
    let project =
        monorepo("dart = { dir = \"apps/mobile/lib/app/data/api\", layout = \"sources\" }\n")?;
    let dir = project.path();
    let api = dir.join("apps/mobile/lib/app/data/api");
    assert_success(&rok(dir, &["gen"])?);
    assert_eq!(
        listing(&api)?,
        ["api.dart", "client.dart", "models.dart", "runtime.dart"]
    );
    let exports = fs::read_to_string(api.join("api.dart"))?;
    assert!(exports.contains("export 'client.dart';\n"), "{exports}");
    assert!(exports.contains("export 'models.dart';\n"), "{exports}");
    assert!(exports.contains("export 'runtime.dart'\n"), "{exports}");
    assert!(!exports.contains("src/"), "{exports}");
    let client = fs::read_to_string(api.join("client.dart"))?;
    assert!(client.contains("import 'runtime.dart';"), "{client}");
    assert_success(&rok(dir, &["gen", "check"])?);
    Ok(())
}

/// `rok gen` owns only its marked files: an App's own file beside the
/// Client stays, a marked file no longer emitted goes.
#[test]
fn a_sources_directory_keeps_the_apps_own_files() -> Result<()> {
    let project = monorepo("ts = { dir = \"apps/web/src/lib/api\", layout = \"sources\" }\n")?;
    let dir = project.path();
    let api = dir.join("apps/web/src/lib/api");
    fs::create_dir_all(&api)?;
    let mine = api.join("session.ts");
    fs::write(&mine, "export const session = 1\n")?;
    assert_success(&rok(dir, &["gen"])?);
    let old = api.join("old.ts");
    fs::write(&old, MARKER)?;
    let check = rok(dir, &["gen", "check"])?;
    assert!(!check.status.success());
    assert!(text(&check.stdout).contains("stale apps/web/src/lib/api/old.ts"));

    assert_success(&rok(dir, &["gen"])?);
    assert!(!old.exists());
    assert_eq!(fs::read_to_string(&mine)?, "export const session = 1\n");
    assert_success(&rok(dir, &["gen", "check"])?);
    Ok(())
}

#[test]
fn a_table_without_a_layout_is_a_package() -> Result<()> {
    let project = monorepo("ts = { dir = \"clients/ts\" }\n")?;
    let dir = project.path();
    assert_success(&rok(dir, &["gen"])?);
    assert!(dir.join("clients/ts/README.md").is_file());
    assert!(dir.join("clients/ts/src/index.ts").is_file());
    Ok(())
}

#[test]
fn a_wrong_entry_fails_naming_it() -> Result<()> {
    for (clients, expected) in [
        (
            "ts = { dir = \"web\", layout = \"flat\" }\n",
            "`clients.ts.layout`: \"flat\" is not a layout (package, sources)",
        ),
        (
            "rust = { dir = \"client\", layout = \"sources\" }\n",
            "`clients.rust.layout`: the rust Client is a package only",
        ),
        (
            "dart = { path = \"mobile\" }\n",
            "`clients.dart.path`: a client takes `dir` and `layout`",
        ),
        (
            "dart = { layout = \"sources\" }\n",
            "`clients.dart` names no `dir`",
        ),
    ] {
        let project = monorepo(clients)?;
        let output = rok(project.path(), &["gen"])?;
        assert!(!output.status.success(), "{clients}");
        let stderr = text(&output.stderr);
        assert!(stderr.contains(expected), "{clients}: {stderr}");
    }
    Ok(())
}
