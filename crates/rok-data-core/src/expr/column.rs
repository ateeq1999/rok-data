//! A column of a model, and the expressions it builds.

use std::fmt;
use std::marker::PhantomData;

use crate::{Model, Projected, Value};

use super::{Cond, Direction, Expr, Order, Projection, Render, SubKind, Term};

/// A column of model `M`.
///
/// `#[derive(Model)]` generates one associated constant per field, named
/// after the field in `SCREAMING_SNAKE_CASE` (`User::EMAIL`, `User::ID`, …).
/// Columns are tied to their model, so a `Post` column can't accidentally be
/// used to filter `User`s.
pub struct Column<M> {
    name: &'static str,
    _model: PhantomData<fn() -> M>,
}

impl<M> Column<M> {
    /// Create a column handle. Normally generated by `#[derive(Model)]`.
    pub const fn new(name: &'static str) -> Self {
        Self {
            name,
            _model: PhantomData,
        }
    }

    /// The column name in the database.
    pub const fn name(&self) -> &'static str {
        self.name
    }
}

impl<M: Model> Column<M> {
    /// The column as a SQL value expression.
    pub(crate) fn term(self) -> Term {
        Term::Column {
            table: M::TABLE,
            name: self.name,
        }
    }

    /// `"table"."column"`, for raw SQL fragments.
    fn qualified(self) -> String {
        crate::sql::qualified(M::TABLE, self.name)
    }

    fn cmp(self, op: &'static str, value: impl Into<Value>) -> Expr<M> {
        Expr::new(Cond::Cmp {
            term: self.term(),
            op,
            value: value.into(),
        })
    }

    /// `column = value`
    pub fn eq(self, value: impl Into<Value>) -> Expr<M> {
        self.cmp("=", value)
    }

    /// `column <> value`
    pub fn ne(self, value: impl Into<Value>) -> Expr<M> {
        self.cmp("<>", value)
    }

    /// `column > value`
    pub fn gt(self, value: impl Into<Value>) -> Expr<M> {
        self.cmp(">", value)
    }

    /// `column >= value`
    pub fn gte(self, value: impl Into<Value>) -> Expr<M> {
        self.cmp(">=", value)
    }

    /// `column < value`
    pub fn lt(self, value: impl Into<Value>) -> Expr<M> {
        self.cmp("<", value)
    }

    /// `column <= value`
    pub fn lte(self, value: impl Into<Value>) -> Expr<M> {
        self.cmp("<=", value)
    }

    /// `column LIKE pattern`
    pub fn like(self, pattern: impl Into<Value>) -> Expr<M> {
        self.cmp("LIKE", pattern)
    }

    /// `column NOT LIKE pattern`
    pub fn not_like(self, pattern: impl Into<Value>) -> Expr<M> {
        self.cmp("NOT LIKE", pattern)
    }

    /// Case-insensitive `column ILIKE pattern`
    pub fn ilike(self, pattern: impl Into<Value>) -> Expr<M> {
        self.cmp("ILIKE", pattern)
    }

    /// `column LIKE '%text%'`, escaping `%`, `_` and `\` in `text`.
    pub fn contains(self, text: &str) -> Expr<M> {
        self.like(format!("%{}%", escape_like(text)))
    }

    /// `column LIKE 'text%'`, escaping `%`, `_` and `\` in `text`.
    pub fn starts_with(self, text: &str) -> Expr<M> {
        self.like(format!("{}%", escape_like(text)))
    }

    /// `column LIKE '%text'`, escaping `%`, `_` and `\` in `text`.
    pub fn ends_with(self, text: &str) -> Expr<M> {
        self.like(format!("%{}", escape_like(text)))
    }

    /// `column IN (…)`. An empty list matches nothing.
    pub fn is_in<V: Into<Value>>(self, values: impl IntoIterator<Item = V>) -> Expr<M> {
        Expr::new(Cond::In {
            table: M::TABLE,
            column: self.name,
            values: values.into_iter().map(Into::into).collect(),
            negated: false,
        })
    }

    /// `column NOT IN (…)`. An empty list matches everything.
    pub fn not_in<V: Into<Value>>(self, values: impl IntoIterator<Item = V>) -> Expr<M> {
        Expr::new(Cond::In {
            table: M::TABLE,
            column: self.name,
            values: values.into_iter().map(Into::into).collect(),
            negated: true,
        })
    }

    /// `column IN (subquery)`, where the subquery selects one column.
    ///
    /// ```ignore
    /// // Users who wrote a post with more than 100 views.
    /// User::filter(User::ID.in_subquery(
    ///     Post::filter(Post::VIEWS.gt(100)).select(Post::AUTHOR_ID),
    /// ))
    /// ```
    pub fn in_subquery<N: Model>(self, subquery: Projected<N>) -> Expr<M> {
        Expr::new(Cond::Sub {
            kind: SubKind::In {
                table: M::TABLE,
                column: self.name,
                negated: false,
            },
            render: Render::new(move |sql| subquery.write_into(sql)),
        })
    }

    /// `column NOT IN (subquery)`. Beware that `NOT IN` matches nothing if
    /// the subquery returns any `NULL`; prefer [`Expr::not_exists`] then.
    pub fn not_in_subquery<N: Model>(self, subquery: Projected<N>) -> Expr<M> {
        Expr::new(Cond::Sub {
            kind: SubKind::In {
                table: M::TABLE,
                column: self.name,
                negated: true,
            },
            render: Render::new(move |sql| subquery.write_into(sql)),
        })
    }

    /// Compare this column to a column of the *enclosing* query's model, for
    /// correlated subqueries: `"posts"."author_id" = "users"."id"`.
    ///
    /// ```ignore
    /// // Users with at least one post.
    /// User::filter(Expr::exists(Post::filter(Post::AUTHOR_ID.eq_outer(User::ID))))
    /// ```
    pub fn eq_outer<O: Model>(self, outer: Column<O>) -> Expr<M>
    where
        M: Model,
    {
        Expr::new(Cond::Columns {
            left: (M::TABLE, self.name),
            op: "=",
            right: (O::TABLE, outer.name),
        })
    }

    /// `column BETWEEN low AND high`
    pub fn between(self, low: impl Into<Value>, high: impl Into<Value>) -> Expr<M> {
        Expr::new(Cond::Between {
            table: M::TABLE,
            column: self.name,
            low: low.into(),
            high: high.into(),
        })
    }

    /// `column IS NULL`
    pub fn is_null(self) -> Expr<M> {
        Expr::new(Cond::Null {
            table: M::TABLE,
            column: self.name,
            negated: false,
        })
    }

    /// `column IS NOT NULL`
    pub fn is_not_null(self) -> Expr<M> {
        Expr::new(Cond::Null {
            table: M::TABLE,
            column: self.name,
            negated: true,
        })
    }

    // ----- PostgreSQL: arrays ------------------------------------------------

    /// `column = ANY($1)` with a single array parameter — like
    /// [`is_in`](Self::is_in), but one parameter however many values, so it
    /// suits very large lists.
    pub fn eq_any<T>(self, values: impl IntoIterator<Item = T>) -> Expr<M>
    where
        Vec<T>: Into<Value>,
    {
        let values: Vec<T> = values.into_iter().collect();
        Expr::raw(format!("{} = ANY(?)", self.qualified()), [values.into()])
    }

    /// Array column contains every element of `values` (`column @> $1`).
    pub fn array_contains(self, values: impl Into<Value>) -> Expr<M> {
        self.cmp("@>", values)
    }

    /// Array column shares at least one element with `values` (`column && $1`).
    pub fn array_overlaps(self, values: impl Into<Value>) -> Expr<M> {
        self.cmp("&&", values)
    }

    /// Array column contains `value` (`$1 = ANY(column)`).
    pub fn array_has(self, value: impl Into<Value>) -> Expr<M> {
        Expr::raw(format!("? = ANY({})", self.qualified()), [value.into()])
    }

    // ----- PostgreSQL: JSONB -------------------------------------------------

    /// JSONB column has the top-level key `key` (`column ? $1`).
    pub fn json_has_key(self, key: &str) -> Expr<M> {
        self.cmp("?", key)
    }

    /// JSONB column has any of `keys` (`column ?| $1`).
    pub fn json_has_any_key<K: Into<String>>(self, keys: impl IntoIterator<Item = K>) -> Expr<M> {
        let keys: Vec<String> = keys.into_iter().map(Into::into).collect();
        self.cmp("?|", keys)
    }

    /// JSONB column has all of `keys` (`column ?& $1`).
    pub fn json_has_all_keys<K: Into<String>>(self, keys: impl IntoIterator<Item = K>) -> Expr<M> {
        let keys: Vec<String> = keys.into_iter().map(Into::into).collect();
        self.cmp("?&", keys)
    }

    /// JSONB column contains `json` (`column @> $1`), e.g.
    /// `User::PREFS.json_contains(json!({"theme": "dark"}))`.
    #[cfg(feature = "json")]
    pub fn json_contains(self, json: serde_json::Value) -> Expr<M> {
        self.cmp("@>", json)
    }

    /// The text value at `key` of a JSON/JSONB column (`column ->> $1`), to
    /// filter, select or order by: `User::PREFS.json_text("theme").eq("dark")`.
    pub fn json_text(self, key: &str) -> Projection<M> {
        Projection::raw(format!("{} ->> ?", self.qualified()), [key])
    }

    /// The text value at a nested path (`column #>> $1`):
    /// `Event::DATA.json_path_text(["user", "id"])`.
    pub fn json_path_text<K: Into<String>>(
        self,
        path: impl IntoIterator<Item = K>,
    ) -> Projection<M> {
        let path: Vec<String> = path.into_iter().map(Into::into).collect();
        Projection::raw(format!("{} #>> ?", self.qualified()), [path])
    }

    // ----- PostgreSQL: full-text search ----------------------------------------

    /// Full-text search on a text column with the server's default text
    /// search configuration:
    /// `to_tsvector(column) @@ websearch_to_tsquery($1)`.
    ///
    /// `query` uses web-search syntax: `rust -java "query builder" or orm`.
    /// For speed, index `to_tsvector(column)` or use a generated `tsvector`
    /// column with [`ts_matches`](Self::ts_matches).
    pub fn search(self, query: &str) -> Expr<M> {
        Expr::raw(
            format!(
                "to_tsvector({}) @@ websearch_to_tsquery(?)",
                self.qualified()
            ),
            [query],
        )
    }

    /// [`search`](Self::search) with an explicit configuration such as
    /// `"english"` (enables stemming and stop words).
    pub fn search_in(self, config: &str, query: &str) -> Expr<M> {
        Expr::raw(
            format!(
                "to_tsvector(?::regconfig, {}) @@ websearch_to_tsquery(?::regconfig, ?)",
                self.qualified()
            ),
            [config, config, query],
        )
    }

    /// Match a `tsvector` column: `column @@ websearch_to_tsquery($1)`.
    pub fn ts_matches(self, query: &str) -> Expr<M> {
        Expr::raw(
            format!("{} @@ websearch_to_tsquery(?)", self.qualified()),
            [query],
        )
    }

    /// Relevance of a text column for `query`, to order results:
    /// `.order_by(Post::BODY.search_rank("rust orm").desc())`.
    pub fn search_rank(self, query: &str) -> Projection<M> {
        Projection::raw(
            format!(
                "ts_rank(to_tsvector({}), websearch_to_tsquery(?))",
                self.qualified()
            ),
            [query],
        )
    }

    /// `COUNT(column)` — number of non-`NULL` values.
    pub fn count(self) -> Projection<M> {
        Projection::func("COUNT", Some((M::TABLE, self.name)), false)
    }

    /// `COUNT(DISTINCT column)`
    pub fn count_distinct(self) -> Projection<M> {
        Projection::func("COUNT", Some((M::TABLE, self.name)), true)
    }

    /// `SUM(column)`. PostgreSQL returns `BIGINT` for `SMALLINT`/`INTEGER`
    /// columns and `NUMERIC` for `BIGINT` columns; use
    /// [`Projection::cast`] to pick the Rust type you decode into.
    pub fn sum(self) -> Projection<M> {
        Projection::func("SUM", Some((M::TABLE, self.name)), false)
    }

    /// `AVG(column)`, returned as `NUMERIC` for integer columns; see
    /// [`Projection::cast`].
    pub fn avg(self) -> Projection<M> {
        Projection::func("AVG", Some((M::TABLE, self.name)), false)
    }

    /// `MIN(column)`
    pub fn min(self) -> Projection<M> {
        Projection::func("MIN", Some((M::TABLE, self.name)), false)
    }

    /// `MAX(column)`
    pub fn max(self) -> Projection<M> {
        Projection::func("MAX", Some((M::TABLE, self.name)), false)
    }

    /// Ascending ordering on this column.
    pub fn asc(self) -> Order<M> {
        Order::new(M::TABLE, self.name, Direction::Asc)
    }

    /// Descending ordering on this column.
    pub fn desc(self) -> Order<M> {
        Order::new(M::TABLE, self.name, Direction::Desc)
    }
}

impl<M> Clone for Column<M> {
    fn clone(&self) -> Self {
        *self
    }
}

impl<M> Copy for Column<M> {}

impl<M> fmt::Debug for Column<M> {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_tuple("Column").field(&self.name).finish()
    }
}

impl<M> fmt::Display for Column<M> {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(self.name)
    }
}

pub(crate) fn escape_like(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    for c in text.chars() {
        if matches!(c, '%' | '_' | '\\') {
            out.push('\\');
        }
        out.push(c);
    }
    out
}
