//! The gRPC framework of the API generator (engine ADR 0028): `[api]
//! framework = "grpc"` writes one `proto/<resource>.proto` per Resource,
//! derived from the same Feature model as the HTTP features, and the drift
//! check covers the files.

use std::fs;
use std::path::{Path, PathBuf};

use anyhow::Result;
use tempfile::TempDir;

/// The axum fixture's schema: the shared fixture of the API generator.
fn fixture_schema() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/axum-app/migrations/0001_notes.sql")
}

const CONFIG: &str = "schema = \"schema.sql\"
output = \"src/db\"
derive = [\"serde\", \"validate\"]

[api]
output = \"src/features\"
framework = \"grpc\"
";

struct Project {
    dir: TempDir,
}

impl Project {
    /// A crate named `shop-api` whose schema is `schema`, configured by
    /// `config`.
    fn new(schema: &str, config: &str) -> Result<Self> {
        let dir = TempDir::new()?;
        fs::write(
            dir.path().join("Cargo.toml"),
            "[package]\nname = \"shop-api\"\nversion = \"0.1.0\"\nedition = \"2024\"\n",
        )?;
        fs::write(dir.path().join("schema.sql"), schema)?;
        fs::write(dir.path().join("rok-data-sqlc.toml"), config)?;
        Ok(Project { dir })
    }

    fn fixture() -> Result<Self> {
        Project::new(&fs::read_to_string(fixture_schema())?, CONFIG)
    }

    fn path(&self, path: &str) -> PathBuf {
        self.dir.path().join(path)
    }

    fn read(&self, path: &str) -> Result<String> {
        Ok(fs::read_to_string(self.path(path))?)
    }

    fn config(&self) -> Result<rok_data_sqlc::Config> {
        rok_data_sqlc::load_config(&self.path("rok-data-sqlc.toml"))
    }

    fn generate(&self) -> Result<rok_data_sqlc::Report> {
        Ok(rok_data_sqlc::generate(&self.config()?)?)
    }

    fn check(&self) -> rok_data_sqlc::Result<rok_data_sqlc::Report> {
        let mut config = self.config().expect("the config loads");
        config.check = true;
        rok_data_sqlc::generate(&config)
    }
}

/// `framework = "grpc"` loads, and generation writes one `.proto` per
/// Resource under `proto/`, marked generated: proto3, in the project's
/// package.
#[test]
fn grpc_writes_a_proto_per_resource() -> Result<()> {
    let project = Project::fixture()?;
    project.generate()?;

    for resource in ["accounts", "notes", "labels"] {
        let proto = project.read(&format!("proto/{resource}.proto"))?;
        assert!(
            proto.starts_with("// @generated by rok-data-sqlc. Do not edit by hand.\n"),
            "{proto}"
        );
        assert!(proto.contains("\nsyntax = \"proto3\";\n"), "{proto}");
        assert!(proto.contains("\npackage shop_api.v1;\n"), "{proto}");
    }
    // A join table is no Resource: it has no feature, so no service.
    assert!(!project.path("proto/note_labels.proto").exists());
    Ok(())
}

