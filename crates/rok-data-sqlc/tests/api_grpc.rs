/// Every column type maps per engine ADR 0028; a nullable column is
/// `optional`; an SQL enum is a proto enum whose first value is
/// `<ENUM>_UNSPECIFIED = 0`.
#[test]
fn columns_map_to_proto_types() -> Result<()> {
    let project = Project::new(TYPES_SCHEMA, CONFIG)?;
    project.generate()?;
    let proto = project.read("proto/gadgets.proto")?;

    let row = "message Gadget {
  enum Mood {
    MOOD_UNSPECIFIED = 0;
    MOOD_HAPPY = 1;
    MOOD_VERY_SAD = 2;
  }

  int64 id = 1;
  string code = 2;
  string name = 3;
  int32 small = 4;
  int32 count = 5;
  optional int64 big = 6;
  float ratio = 7;
  double score = 8;
  string price = 9;
  bool active = 10;
  bytes blob = 11;
  google.protobuf.Timestamp made_on = 12;
  google.protobuf.Timestamp seen_at = 13;
  google.protobuf.Timestamp created_at = 14;
  google.protobuf.Struct meta = 15;
  optional google.protobuf.Struct extra = 16;
  Mood mood = 17;
  optional string nickname = 18;
}
";
    assert!(proto.contains(row), "{proto}");
    // The inputs name the row's enum.
    assert!(proto.contains("  Gadget.Mood mood = 16;\n"), "{proto}");
    for import in ["timestamp", "struct"] {
        assert!(
            proto.contains(&format!("\nimport \"google/protobuf/{import}.proto\";\n")),
            "{proto}"
        );
    }

    // A Resource with neither a time nor JSON imports neither.
    let plain = project.read("proto/plain.proto")?;
    assert!(!plain.contains("import"), "{plain}");
    Ok(())
}

/// `[api.skip]` leaves an endpoint's RPC, and its messages, out.
#[test]
fn a_skipped_endpoint_has_no_rpc() -> Result<()> {
    let project = Project::new(
        "CREATE TABLE plain (id BIGSERIAL PRIMARY KEY, name TEXT NOT NULL);",
        &format!("{CONFIG}\n[api.skip]\nplain = [\"remove\", \"update\"]\n"),
    )?;
    project.generate()?;
    let proto = project.read("proto/plain.proto")?;
    assert!(
        proto.contains("  rpc Get(GetPlainRequest) returns (Plain);\n"),
        "{proto}"
    );
    for absent in [
        "rpc Delete",
        "rpc Update",
        "DeletePlainRequest",
        "UpdatePlainRequest",
    ] {
        assert!(!proto.contains(absent), "{absent}\n{proto}");
    }
    Ok(())
}

/// The drift check reports a hand-edited `.proto` as changed, and a
/// generated one no Resource makes any more as stale; hand-written protos
/// beside them are the user's.
#[test]
fn the_drift_check_covers_the_protos() -> Result<()> {
    let project = Project::fixture()?;
    project.generate()?;
    project.check().expect("a fresh generation has no drift");

    let notes = project.path("proto/notes.proto");
    let edited = fs::read_to_string(&notes)?.replace("string title = 4;", "string headline = 4;");
    fs::write(&notes, edited)?;
    let old = project.path("proto/drafts.proto");
    fs::write(
        &old,
        "// @generated by rok-data-sqlc. Do not edit by hand.\n",
    )?;
    fs::write(project.path("proto/custom.proto"), "syntax = \"proto3\";\n")?;

    let error = project.check().unwrap_err();
    assert_eq!(
        error.report().changed,
        std::slice::from_ref(&notes),
        "{error:?}"
    );
    assert_eq!(
        error.report().stale,
        std::slice::from_ref(&old),
        "{error:?}"
    );

    project.generate()?;
    assert!(!old.exists());
    assert!(project.path("proto/custom.proto").exists());
    project.check().expect("regeneration fixes the drift");
    Ok(())
}

/// Each feature's gRPC service, instead of routes and handlers: a tonic
/// service implemented on the feature's service, reading each request
/// message into the feature's DTOs and calling the service trait the HTTP
/// handlers call. The DTOs, the trait and `service.rs` stay.
#[test]
fn a_feature_gets_a_grpc_service_over_its_service_trait() -> Result<()> {
    let project = Project::fixture()?;
    project.generate()?;

    for gone in ["routes.rs", "handlers.rs"] {
        assert!(
            !project
                .path(&format!("src/features/labels/{gone}"))
                .exists(),
            "{gone}"
        );
    }
    for kept in [
        "dto.rs",
        "service_api.rs",
        "service.rs",
        "model.rs",
        "repo.rs",
    ] {
        assert!(
            project
                .path(&format!("src/features/labels/{kept}"))
                .exists(),
            "{kept}"
        );
    }
    let module = project.read("src/features/labels/mod.rs")?;
    assert!(module.contains("\npub mod grpc;\n"), "{module}");
    assert!(!module.contains("routes"), "{module}");

    let service = project.read("src/features/labels/grpc.rs")?;
    for expected in [
        "// @generated by rok-data-sqlc. Do not edit by hand.\n",
        "use super::super::proto::labels_service_server::LabelsService as LabelsRpc;\n",
        "#[tonic::async_trait]\nimpl LabelsRpc for LabelsService {\n",
        "    async fn get(\n        &self,\n        request: Request<proto::GetLabelRequest>,\n    ) -> Result<Response<proto::Label>, Status> {\n",
        "        let row = LabelsServiceApi::get_one(self, id).await?;\n",
        "        let input = validated(CreateLabelDto {\n",
        "        let row = LabelsServiceApi::create(self, input).await?;\n",
        "        let row = LabelsServiceApi::update(self, id, input).await?;\n",
        "        LabelsServiceApi::remove(self, id).await?;\n",
        "        Ok(Response::new(proto::DeleteLabelResponse {}))\n",
        "impl TryFrom<Label> for proto::Label {\n",
    ] {
        assert!(service.contains(expected), "{expected}\n{service}");
    }
    // The list answers the page's fields.
    for expected in [
        "            page: message.page,\n            per_page: message.per_page,\n",
        "            total: page.total,\n            page: page.page,\n            per_page: page.per_page,\n",
    ] {
        assert!(service.contains(expected), "{expected}\n{service}");
    }
    // Neither the HTTP framework nor the OpenAPI document reaches it.
    assert!(!service.contains("axum"), "{service}");
    assert!(
        !project
            .read("src/features/labels/dto.rs")?
            .contains("utoipa")
    );

    let root = project.read("src/features/generated.rs")?;
    for expected in [
        "    tonic::include_proto!(\"shop_api.v1\");\n",
        "pub fn routes(pool: &PgPool) -> Routes {\n",
        "        .add_service(LabelsServiceServer::new(labels))\n",
    ] {
        assert!(root.contains(expected), "{expected}\n{root}");
    }
    Ok(())
}

/// The one place errors become statuses: `shared/grpc.rs`, generated, maps
/// each `AppError` to its gRPC code, the field errors of a validation
/// failure into the status's details.
#[test]
fn the_status_mapping_is_generated_once() -> Result<()> {
    let project = Project::fixture()?;
    project.generate()?;
    let shared = project.read("src/shared/grpc.rs")?;
    for expected in [
        "impl From<AppError> for Status {\n",
        "\"not_found\" => Code::NotFound,",
        "\"unauthorized\" => Code::Unauthenticated,",
        "\"forbidden\" => Code::PermissionDenied,",
        "\"conflict\" => Code::AlreadyExists,",
        "\"validation_failed\" => return invalid(error),",
        "Code::InvalidArgument",
        "add_bad_request_violation",
        "Status::internal(INTERNAL_MESSAGE)",
    ] {
        assert!(shared.contains(expected), "{expected}\n{shared}");
    }
    // No feature maps an error itself.
    let service = project.read("src/features/labels/grpc.rs")?;
    assert!(!service.contains("Code::"), "{service}");
    // gRPC needs no HTTP framework: the shared tools name none.
    for tool in ["pagination.rs", "response.rs", "validation.rs", "grpc.rs"] {
        let text = project.read(&format!("src/shared/{tool}"))?;
        assert!(!text.contains("axum"), "{tool}\n{text}");
    }
    assert!(!project.path("src/shared/health.rs").exists());
    Ok(())
}

