//! `generate`: its flags, the [`Config`] they resolve to over the JSON
//! payload and the config file, and the run.

use std::path::PathBuf;

use anyhow::Result;

use super::args::{DeriveArg, ExtractorArg, FrameworkArg};
use super::print::print_report;
use crate::config_file::{self, FileConfig};
use crate::{ApiFramework, Config, Derive, Extractor};

#[derive(Debug, Clone, Default, clap::Args)]
#[allow(clippy::struct_excessive_bools, reason = "independent clap switches")]
pub(super) struct GenerateArgs {
    /// Schema/migration SQL file, or a directory of migrations read in
    /// filename order (`*.down.sql` skipped); repeat to combine inputs
    /// [default: `schema` from rok-data-sqlc.toml]
    #[arg(short, long, value_name = "PATH")]
    schema: Vec<PathBuf>,

    /// Output directory [default: src/db]
    #[arg(short, long, value_name = "DIR")]
    output: Option<PathBuf>,

    /// Generate this table and regenerate those already generated; skip the rest
    #[arg(short, long, value_name = "TABLE")]
    resource: Option<String>,

    /// List planned writes and refusals without touching the filesystem
    #[arg(short = 'n', long)]
    dry_run: bool,

    /// Write nothing; list missing, changed, and stale files and exit 1 if any
    #[arg(short = 'k', long)]
    check: bool,

    /// Regenerate whenever the schema, the query files or the config file
    /// change, until interrupted; migrations are never applied
    #[arg(short = 'W', long, conflicts_with_all = ["check", "dry_run"])]
    pub(super) watch: bool,

    /// Overwrite existing files that were not generated by rok-data-sqlc
    #[arg(short, long)]
    force: bool,

    /// Annotated query file (generates `queries.rs`) or directory (one
    /// `queries/<stem>.rs` module per `.sql` file); repeatable
    #[arg(short, long, value_name = "PATH")]
    queries: Vec<PathBuf>,

    /// Skip unsupported tables and queries with warnings instead of failing
    #[arg(short, long)]
    lenient: bool,

    /// Read options from this config file instead of discovering
    /// rok-data-sqlc.toml in the current directory or its parents
    #[arg(short, long, value_name = "FILE")]
    config: Option<PathBuf>,

    /// Options as JSON in the shape of rok-data-sqlc.toml: inline, `@FILE`, or
    /// `-` for stdin; paths resolve against the current directory
    #[arg(short, long, value_name = "JSON|@FILE|-", allow_hyphen_values = true)]
    json: Option<String>,

    /// Also derive this for the generated types: `serde` adds
    /// `Serialize`/`Deserialize`, `validate` adds schema-derived
    /// `rok_data::Input` to inputs and patches (needs `serde`);
    /// repeatable [default: `derive` from rok-data-sqlc.toml]
    #[arg(short, long, value_name = "NAME", value_enum)]
    derive: Vec<DeriveArg>,

    /// Generate a validated-body extractor for this framework into `http/`
    /// (needs `-d validate`); repeatable [default: `extractors` from
    /// rok-data-sqlc.toml]
    #[arg(short, long, value_name = "FRAMEWORK", value_enum)]
    extractor: Vec<ExtractorArg>,

    /// Generate API features for actix-web into this directory (needs
    /// `-d serde -d validate -e actix_web`) [default: `api.output` from
    /// rok-data-sqlc.toml]
    #[arg(short, long, value_name = "DIR")]
    api_output: Option<PathBuf>,

    /// The web framework the API features are generated for: `actix_web`
    /// (the default) or `axum` (needs `-e` for the same framework)
    /// [default: `api.framework` from rok-data-sqlc.toml]
    #[arg(short = 'w', long, value_name = "FRAMEWORK", value_enum)]
    api_framework: Option<FrameworkArg>,
}

impl GenerateArgs {
    /// The flags of a `check` run: up to date against `config` (or the
    /// discovered file), nothing written.
    pub(super) fn checking(config: Option<PathBuf>, lenient: bool) -> Self {
        Self {
            check: true,
            lenient,
            config,
            ..Self::default()
        }
    }

    /// The config file the run reads: `--config`, or the discovered one.
    pub(super) fn config_file(&self) -> Result<Option<PathBuf>> {
        Ok(match &self.config {
            Some(path) => Some(path.clone()),
            None => config_file::discover(&std::env::current_dir()?),
        })
    }

    /// The run's [`Config`]: flags override the JSON payload, which
    /// overrides the file, which overrides the defaults. Read anew on each
    /// call, so a watch sees an edited config file.
    pub(super) fn resolve(&self) -> Result<Config> {
        let payload = match &self.json {
            Some(arg) => config_file::load_json(arg)?,
            None => FileConfig::default(),
        };
        let file = match self.config_file()? {
            Some(path) => config_file::load(&path)?,
            None => FileConfig::default(),
        };
        let flags = FileConfig {
            schema: self.schema.clone(),
            migrations: None,
            queries: self.queries.clone(),
            output: self.output.clone(),
            resource: self.resource.clone(),
            conventions: Default::default(),
            derive: (!self.derive.is_empty())
                .then(|| self.derive.iter().copied().map(Derive::from).collect()),
            extractors: (!self.extractor.is_empty()).then(|| {
                self.extractor
                    .iter()
                    .copied()
                    .map(Extractor::from)
                    .collect()
            }),
            relationships: Default::default(),
            scopes: Default::default(),
            modules: Default::default(),
            api: config_file::ApiKeys::flags(
                self.api_output.clone(),
                self.api_framework.map(ApiFramework::from),
            ),
        };
        // `--schema` and `--queries` (each given any number of times)
        // replace the lower sources' whole `schema` / `queries` list; an
        // empty Vec means "not set".
        let merged = flags.over(payload.over(file));
        if merged.schema.is_empty() {
            return Err(super::missing_schema().into());
        }
        let defaults = Config::default();
        Ok(Config {
            schema: merged.schema,
            migrations: merged.migrations.unwrap_or(defaults.migrations),
            queries: merged.queries,
            output: merged.output.unwrap_or(defaults.output),
            resource: merged.resource,
            dry_run: self.dry_run,
            check: self.check,
            force: self.force,
            lenient: self.lenient,
            conventions: merged.conventions.resolve(),
            derive: merged.derive.unwrap_or_default(),
            extractors: merged.extractors.unwrap_or_default(),
            relationships: merged.relationships,
            scopes: merged.scopes,
            modules: merged.modules,
            api: merged.api.resolve(),
        })
    }
}

/// Generates once with `args`, printing the report.
pub(super) fn run(args: &GenerateArgs) -> Result<()> {
    if args.watch {
        return super::watch::watch(args);
    }
    generate(&args.resolve()?)
}

pub(super) fn generate(config: &Config) -> Result<()> {
    match crate::generate(config) {
        Ok(report) => {
            print_report(config, &report);
            Ok(())
        }
        Err(err) => {
            print_report(config, err.report());
            Err(err.into())
        }
    }
}
