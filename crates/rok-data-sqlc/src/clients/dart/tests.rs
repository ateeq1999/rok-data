use std::path::{Path, PathBuf};

use serde_json::{Value, json};

use super::*;

/// The monorepo template's api App's document, read.
fn monorepo() -> Document {
    let text = rok_templates::catalog::files("monorepo")
        .and_then(|files| {
            files
                .iter()
                .find(|file| file.path == "apps/api/openapi.json")
        })
        .map(|file| String::from_utf8_lossy(file.bytes).into_owned())
        .unwrap_or_else(|| panic!("the monorepo template ships no apps/api/openapi.json"));
    Document::parse(&text).unwrap_or_else(|err| panic!("{err}"))
}

fn emitted(document: &Document) -> Vec<(PathBuf, String)> {
    emit(document).unwrap_or_else(|err| panic!("{err}"))
}

fn file<'a>(files: &'a [(PathBuf, String)], path: &str) -> &'a str {
    files
        .iter()
        .find(|(at, _)| at == Path::new(path))
        .map(|(_, text)| text.as_str())
        .unwrap_or_else(|| panic!("no {path}"))
}

/// A document of `paths` and component `schemas`.
fn document(paths: Value, schemas: Value) -> Document {
    let json = json!({
        "openapi": "3.1.0", "info": {"title": "t", "version": "1"},
        "paths": paths, "components": {"schemas": schemas},
    })
    .to_string();
    Document::parse(&json).unwrap_or_else(|err| panic!("{err}"))
}

fn emit_err(document: &Document) -> String {
    match emit(document) {
        Ok(_) => panic!("emitted, but should not have"),
        Err(err) => err.to_string(),
    }
}

#[test]
fn every_file_carries_the_generated_marker() {
    let files = emitted(&monorepo());
    let paths: Vec<&Path> = files.iter().map(|(path, _)| path.as_path()).collect();
    assert_eq!(
        paths,
        [
            ".gitignore",
            "README.md",
            "analysis_options.yaml",
            "lib/api_client.dart",
            "lib/src/client.dart",
            "lib/src/models.dart",
            "lib/src/runtime.dart",
            "pubspec.yaml",
        ]
        .map(Path::new)
    );
    for (path, text) in &files {
        let first = text.lines().next().unwrap_or("");
        assert!(
            first.contains("@generated by rok-data-sqlc"),
            "{} lacks the marker: {first}",
            path.display()
        );
    }
}

/// Each operation is a typed method of its tag's class: path parameters,
/// then the body, positionally; the query by name; then the options.
#[test]
fn methods_are_typed_per_operation() {
    let files = emitted(&monorepo());
    let client = file(&files, "lib/src/client.dart");
    assert!(client.contains("  UsersApi get users => UsersApi._(_transport);\n"));
    assert!(client.contains(
        "  Future<UserResponse> update(\n    String id,\n    UpdateUserDto body, {\n    \
         RequestOptions? options,\n  }) => _transport.json<UserResponse>(\n    Call(\n      \
         'PATCH',\n      '/api/v1/users/${Uri.encodeComponent(id)}',\n      \
         json: body.toJson(),\n      secured: true,\n    ),\n    \
         (json) => UserResponse.fromJson(json as Map<String, Object?>),\n    options,\n  );\n"
    ));
    assert!(client.contains(
        "  Future<PaginatedResponseUserResponse> list({\n    int? page,\n    int? perPage,\n    \
         String? q,\n    UserSort? sort,\n    SortOrder? order,\n    RequestOptions? options,\n  })"
    ));
    assert!(client.contains(
        "query: {'page': page, 'per_page': perPage, 'q': q, 'sort': sort?.toJson(), \
         'order': order?.toJson()},"
    ));
    // A public operation sends no token; raw bytes in and out; no body.
    assert!(client.contains(
        "  Future<LoginResponse> login(\n    CredentialsDto body, {\n    RequestOptions? options,\n  \
         }) => _transport.json<LoginResponse>(\n    Call(\n      'POST',\n      \
         '/api/v1/auth/login',\n      json: body.toJson(),\n    ),\n"
    ));
    assert!(client.contains("    Bytes body, {\n    String? filename,\n"));
    assert!(client.contains("  Future<Bytes> content(\n"));
    assert!(client.contains("  Future<void> remove(\n    String id, {\n    bool? permanent,\n"));
    // Two `verify`s of `auth`, told apart by where their paths part.
    assert!(client.contains("  Future<TokenResponse> verify2fa(\n"));
    assert!(client.contains("  Future<MessageResponse> verifyEmail(\n"));
}

#[test]
fn models_follow_the_schemas() {
    let files = emitted(&monorepo());
    let models = file(&files, "lib/src/models.dart");
    assert!(models.contains("enum Role {\n  user('user'),\n  admin('admin');\n"));
    assert!(models.contains("  final String? avatarUrl;\n"));
    assert!(models.contains("    avatarUrl: json['avatar_url'] as String?,\n"));
    assert!(models.contains("    'avatar_url': ?avatarUrl,\n"));
    assert!(models.contains("  final Role role;\n"));
    assert!(models.contains("    'role': role.toJson(),\n"));
    // `allOf` is one class of every part's fields.
    let created = models
        .split("final class CreatedApiKeyResponse {")
        .nth(1)
        .and_then(|rest| rest.split("\n}\n").next())
        .unwrap_or_else(|| panic!("no CreatedApiKeyResponse"));
    for field in [
        "final String key;",
        "final ApiKeyScope scope;",
        "final String keyPrefix;",
    ] {
        assert!(created.contains(field), "{field} missing:\n{created}");
    }
    // An inline object shaped like a component is that component.
    assert!(models.contains("  final List<UserResponse> items;\n"));
    assert!(models.contains("  final Map<String, Object?>? details;\n"));
    assert!(models.contains("  final List<String> recoveryCodes;\n"));
    assert!(models.contains("  final Map<String, String> headers;\n"));
}

/// A `oneOf` of objects is a sealed class whose variants are told apart
/// by the keys they require.
#[test]
fn one_of_is_a_sealed_class() {
    let files = emitted(&monorepo());
    let models = file(&files, "lib/src/models.dart");
    assert!(models.contains(
        "sealed class LoginResponse {\n  /// Reads one from its JSON: the variant whose required \
         keys it holds.\n  factory LoginResponse.fromJson(Map<String, Object?> json) {\n    \
         if (json.containsKey('access_token') && json.containsKey('expires_in') && \
         json.containsKey('token_type')) {\n      return TokenResponse.fromJson(json);\n    }\n    \
         if (json.containsKey('pending_token') && json.containsKey('requires_totp')) {\n      \
         return LoginResponsePendingToken.fromJson(json);\n    }\n    \
         throw FormatException('no variant of LoginResponse', json);\n  }\n"
    ));
    assert!(models.contains("final class TokenResponse implements LoginResponse {\n"));
    assert!(models.contains("final class LoginResponsePendingToken implements LoginResponse {\n"));
    assert!(models.contains("  @override\n  Map<String, Object?> toJson() => {\n"));
}

/// A request's optional, nullable field keeps "left out" and "null"
/// apart; a response's reads as a plain nullable.
#[test]
fn request_fields_that_may_be_cleared_are_three_state() {
    let files = emitted(&monorepo());
    let models = file(&files, "lib/src/models.dart");
    assert!(models.contains("  final Nullable<String>? displayName;\n"));
    assert!(models.contains(
        "    displayName: json.containsKey('display_name') ? Nullable(json['display_name'] as \
         String?) : null,\n"
    ));
    assert!(models.contains("    if (displayName case final set?) 'display_name': set.value,\n"));
    assert!(models.contains("    if (role case final set?) 'role': set.value?.toJson(),\n"));
    assert!(models.starts_with(&format!("{HEADER}\nimport 'runtime.dart';\n")));
    // `UserResponse`'s display name is read, never sent.
    assert!(models.contains("  final String? displayName;\n"));
}

