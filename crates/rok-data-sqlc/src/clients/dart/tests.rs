/// What the Dart client cannot type is reported, naming it and where.
#[test]
fn unsupported_constructs_are_reported() {
    let mixed = document(
        json!({}),
        json!({"Bag": {"type": "object", "properties": {"a": {"type": "string"}},
                       "additionalProperties": {"type": "string"}}}),
    );
    assert_eq!(
        emit_err(&mixed),
        "`#/components/schemas/Bag`: an object with both `properties` and \
         `additionalProperties` is not supported by the Dart client"
    );
    let scalars = document(
        json!({}),
        json!({"Id": {"oneOf": [{"type": "string"}, {"type": "integer"}]}}),
    );
    assert_eq!(
        emit_err(&scalars),
        "`#/components/schemas/Id`: a `oneOf` with a variant that is not an object is not \
         supported by the Dart client"
    );
    let list_query = document(
        json!({"/things": {"get": {
            "operationId": "list", "tags": ["things"],
            "parameters": [{"name": "ids", "in": "query",
                            "schema": {"type": "array", "items": {"type": "string"}}}],
            "responses": {"204": {"description": ""}},
        }}}),
        json!({}),
    );
    assert_eq!(
        emit_err(&list_query),
        "`GET /things`, query parameter `ids`: a query parameter that is not a scalar is not \
         supported by the Dart client"
    );
    let reserved = document(json!({}), json!({"Session": {"type": "string"}}));
    assert_eq!(
        emit_err(&reserved),
        "the schema `Session` is `Session` in Dart, a name the client takes already; rename \
         the Rust type (or its `#[schema(as = ...)]`)"
    );
}

/// Emission is stable, and a contract change changes the client where
/// it should and nowhere else.
#[test]
fn a_contract_change_changes_only_what_it_touches() {
    let things = |extra: Value| {
        let mut properties = json!({"id": {"type": "string"}});
        if let (Some(base), Some(extra)) = (properties.as_object_mut(), extra.as_object()) {
            base.extend(extra.clone());
        }
        document(
            json!({"/things": {"get": {
                "operationId": "list", "tags": ["things"],
                "responses": {"200": {"description": "", "content": {"application/json": {
                    "schema": {"type": "array", "items": {"$ref": "#/components/schemas/Thing"}}
                }}}},
            }}}),
            json!({"Thing": {"type": "object", "required": ["id"], "properties": properties}}),
        )
    };
    let before = emitted(&things(json!({})));
    assert_eq!(before, emitted(&things(json!({}))));
    let after = emitted(&things(json!({"label": {"type": ["string", "null"]}})));
    let changed: Vec<&Path> = before
        .iter()
        .zip(&after)
        .filter(|(old, new)| old != new)
        .map(|(old, _)| old.0.as_path())
        .collect();
    assert_eq!(changed, [Path::new("lib/src/models.dart")]);
    let models = file(&after, "lib/src/models.dart");
    assert!(models.contains("  final String? label;\n"));
    assert!(file(&after, "lib/src/client.dart").contains(
        "(json) => (json as List<Object?>).map((v) => Thing.fromJson(v as Map<String, \
         Object?>)).toList(),"
    ));
}

/// The document generated features serve (`tests/api-app`), read: its
/// versioned `documents` take `If-Match` on `PATCH`.
fn api_app() -> Document {
    let path = concat!(
        env!("CARGO_MANIFEST_DIR"),
        "/tests/api-app/tests/expected/openapi.json"
    );
    let text = std::fs::read_to_string(path).unwrap_or_else(|err| panic!("{path}: {err}"));
    Document::parse(&text).unwrap_or_else(|err| panic!("{err}"))
}

/// A header parameter is a named parameter, after the query's and before
/// the options, named after the header in camelCase and `required` when
/// the header is: a versioned row's update takes `ifMatch: version`.
#[test]
fn header_parameters_are_named_parameters() {
    let files = emitted(&api_app());
    let client = file(&files, "lib/src/client.dart");
    assert!(client.contains(
        "  Future<DocumentResponse> update(\n    String id,\n    UpdateDocumentDto body, {\n    \
         required String ifMatch,\n    RequestOptions? options,\n  }) => \
         _transport.json<DocumentResponse>(\n    Call(\n      'PATCH',\n      \
         '/api/v1/documents/${Uri.encodeComponent(id)}',\n      json: body.toJson(),\n      \
         headers: {'If-Match': ifMatch},\n      secured: true,\n    ),\n"
    ), "{client}");
    let runtime = file(&files, "lib/src/runtime.dart");
    assert!(runtime.contains("    this.headers = const {},\n    this.json,"));
    assert!(runtime.contains("  final Map<String, Object?> headers;\n"));
}

/// An optional header is a nullable named parameter, left out when null.
#[test]
fn an_optional_header_is_nullable() {
    let document = document(
        json!({"/things": {"get": {
            "operationId": "list", "tags": ["things"],
            "parameters": [{"name": "X-Trace-Id", "in": "header", "schema": {"type": "string"}}],
            "responses": {"204": {"description": ""}},
        }}}),
        json!({}),
    );
    let files = emitted(&document);
    let client = file(&files, "lib/src/client.dart");
    assert!(
        client.contains(
            "  Future<void> list({\n    String? xTraceId,\n    RequestOptions? options,\n"
        )
    );
    assert!(client.contains("      headers: {'X-Trace-Id': xTraceId},\n"));
}
