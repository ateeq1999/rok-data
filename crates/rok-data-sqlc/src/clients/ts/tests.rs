/// A schema named like one of the runtime's exports cannot be re-exported
/// beside it: the emitter says which, and what to do.
#[test]
fn a_schema_named_like_the_runtime_is_refused() {
    let json = json!({
        "openapi": "3.1.0", "info": {}, "paths": {},
        "components": {"schemas": {"ApiError": {"type": "string"}}},
    })
    .to_string();
    let document = Document::parse(&json).unwrap_or_else(|err| panic!("{err}"));
    let err = emit(&document).err().map(|err| err.to_string());
    assert_eq!(
        err.as_deref(),
        Some(
            "the schema `ApiError` takes the name of the client's `ApiError`; rename the Rust \
             type (or its `#[schema(as = ...)]`)"
        )
    );
}

/// Two operations of one tag sharing an `operationId` on one path (two
/// methods) are told apart by their methods.
#[test]
fn a_shared_name_on_one_path_takes_the_method() {
    let json = json!({
        "openapi": "3.1.0", "info": {},
        "paths": {"/things": {
            "get": {"operationId": "things", "tags": ["t"], "responses": {"204": {"description": ""}}},
            "post": {"operationId": "things", "tags": ["t"], "responses": {"204": {"description": ""}}},
        }},
    })
    .to_string();
    let document = Document::parse(&json).unwrap_or_else(|err| panic!("{err}"));
    let names: Vec<String> = name_operations(&document.operations)
        .into_iter()
        .map(|named| named.name)
        .collect();
    assert_eq!(names, ["thingsGet", "thingsPost"]);
}

