use std::path::{Path, PathBuf};

use serde_json::json;

use super::*;

/// The monorepo template's api App's document, read.
fn monorepo() -> Document {
    let text = rok_templates::catalog::files("monorepo")
        .and_then(|files| {
            files
                .iter()
                .find(|file| file.path == "apps/api/openapi.json")
        })
        .map(|file| String::from_utf8_lossy(file.bytes).into_owned())
        .unwrap_or_else(|| panic!("the monorepo template ships no apps/api/openapi.json"));
    Document::parse(&text).unwrap_or_else(|err| panic!("{err}"))
}

fn emitted(document: &Document) -> Vec<(PathBuf, String)> {
    emit(document).unwrap_or_else(|err| panic!("{err}"))
}

fn file<'a>(files: &'a [(PathBuf, String)], path: &str) -> &'a str {
    files
        .iter()
        .find(|(at, _)| at == Path::new(path))
        .map(|(_, text)| text.as_str())
        .unwrap_or_else(|| panic!("no {path}"))
}

#[test]
fn every_file_carries_the_generated_marker() {
    let files = emitted(&monorepo());
    let paths: Vec<&Path> = files.iter().map(|(path, _)| path.as_path()).collect();
    assert_eq!(
        paths,
        [
            "README.md",
            "src/calls.ts",
            "src/index.ts",
            "src/queries.ts",
            "src/runtime.ts",
            "src/types.ts"
        ]
        .map(Path::new)
    );
    for (path, text) in &files {
        let first = text.lines().next().unwrap_or("");
        assert!(
            first.contains("@generated by rok-data-sqlc"),
            "{} lacks the marker: {first}",
            path.display()
        );
    }
}

/// Each operation is a typed call: path parameters, then the body, then
/// the query, then the options; a public one sends no token.
#[test]
fn calls_are_typed_per_operation() {
    let files = emitted(&monorepo());
    let calls = file(&files, "src/calls.ts");
    assert!(calls.contains(
        "    login: (\n      body: CredentialsDto,\n      options?: RequestOptions\n    ) =>\n      \
         request<LoginResponse>(\n        {\n          operation: \"POST /api/v1/auth/login\",\n          \
         method: \"POST\",\n          \
         path: \"/api/v1/auth/login\",\n          json: body,\n          secured: false,\n          \
         response: \"json\",\n          schema: LoginResponseSchema,\n        },\n        options\n      ),\n"
    ));
    // The schemas a response is checked with are imported as values.
    assert!(calls.contains("  LoginResponseSchema,\n"), "{calls}");
    assert!(calls.contains(
        "    update: (\n      id: string,\n      body: UpdateUserDto,\n      options?: RequestOptions\n    ) =>"
    ));
    assert!(calls.contains("path: `/api/v1/users/${encodeURIComponent(String(id))}`"));
    assert!(calls.contains(
        "    list: (\n      query?: UsersListQuery,\n      options?: RequestOptions\n    ) =>\n      \
         request<PaginatedResponse_UserResponse>("
    ));
    // Raw bytes in, raw bytes out, nothing at all.
    assert!(calls.contains("      body: Blob,\n      query?: MediaUploadQuery,"));
    assert!(calls.contains("blob: body,"));
    assert!(calls.contains("request<Blob>("));
    assert!(calls.contains("request<void>("));
    // Two `verify`s of `auth`, told apart by where their paths part.
    assert!(calls.contains("    verify2fa: (\n"));
    assert!(calls.contains("    verifyEmail: (\n"));
    assert!(calls.contains("  apiKeys: {\n"));
}

#[test]
fn types_follow_the_schemas() {
    let files = emitted(&monorepo());
    let types = file(&files, "src/types.ts");
    assert!(types.starts_with(&format!("{HEADER}{ZOD}\nimport {{ z }} from \"zod\"\n")));
    assert!(types.contains(
        "export const RoleSchema = z.enum([\"user\", \"admin\"])\n\
         export type Role = z.infer<typeof RoleSchema>\n"
    ));
    // Nullable and optional, a reference, a nullable reference.
    assert!(types.contains("  avatar_url: z.string().nullable().optional(),\n"));
    assert!(types.contains("  role: RoleSchema,\n"));
    // A `POST`-only body's optional field is plain optional; a `PATCH`
    // body's keeps `null` apart from left out.
    assert!(types.contains("  scope: ApiKeyScopeSchema.optional(),\n"));
    assert!(types.contains("  role: z.union([z.null(), RoleSchema]).optional(),\n"));
    // Formats, an intersection, a map.
    assert!(types.contains("  id: z.uuid(),\n"));
    assert!(types.contains("  created_at: z.iso.datetime({ offset: true, local: true }),\n"));
    assert!(types.contains(
        "export const CreatedApiKeyResponseSchema = z.intersection(ApiKeyResponseSchema, z.object({\n"
    ));
    assert!(types.contains("  headers: z.record(z.string(), z.string()),\n"));
    // A schema is declared after the ones it refers to.
    let declared = |name: &str| {
        types
            .find(&format!("export const {name} ="))
            .unwrap_or_else(|| panic!("no {name}"))
    };
    assert!(declared("RoleSchema") < declared("AccountResponseSchema"));
    // Query types stay plain types.
    assert!(types.contains("export type UsersListQuery = {\n"));
    assert!(types.contains("  sort?: UserSort\n"));
    // The index re-exports the schemas as values.
    assert!(file(&files, "src/index.ts").contains("export * from \"./types\"\n"));
}

/// Every `GET` has a `queryOptions` factory keyed under its tag; every
/// other operation a `mutationOptions` one whose variables are its one
/// argument, or its arguments by name.
#[test]
fn query_and_mutation_factories_cover_the_operations() {
    let files = emitted(&monorepo());
    let queries = file(&files, "src/queries.ts");
    assert!(queries.starts_with(&format!(
        "{HEADER}{ZOD}\nimport {{ mutationOptions, queryOptions }} from \"@tanstack/react-query\"\n"
    )));
    assert!(queries.contains("  users: [\"users\"] as const,\n"));
    assert!(queries.contains(
        "    list: (query?: UsersListQuery) =>\n      queryOptions({\n        \
         queryKey: [\"users\", \"list\", query ?? {}] as const,\n        \
         queryFn: ({ signal }) => api.users.list(query, { signal }),\n      }),\n"
    ));
    assert!(queries.contains(
        "    getOne: (id: string) =>\n      queryOptions({\n        \
         queryKey: [\"users\", \"getOne\", id] as const,"
    ));
    assert!(queries.contains(
        "    update: (options?: RequestOptions) =>\n      mutationOptions({\n        \
         mutationKey: [\"users\", \"update\"] as const,\n        \
         mutationFn: (variables: { id: string; body: UpdateUserDto }) =>\n          \
         api.users.update(variables.id, variables.body, options),\n      }),\n"
    ));
    assert!(queries.contains(
        "        mutationFn: (body: CredentialsDto) =>\n          api.auth.login(body, options),\n"
    ));
    assert!(queries.contains("        mutationFn: () =>\n          api.auth.resend(options),\n"));
}

