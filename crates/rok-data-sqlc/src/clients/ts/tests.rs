/// Every `GET` has a `queryOptions` factory keyed under its tag; every
/// other operation a `mutationOptions` one whose variables are its one
/// argument, or its arguments by name.
#[test]
fn query_and_mutation_factories_cover_the_operations() {
    let files = emitted(&monorepo());
    let queries = file(&files, "src/queries.ts");
    assert!(queries.starts_with(&format!(
        "{HEADER}\nimport {{ mutationOptions, queryOptions }} from \"@tanstack/react-query\"\n"
    )));
    assert!(queries.contains("  users: [\"users\"] as const,\n"));
    assert!(queries.contains(
        "    list: (query?: UsersListQuery) =>\n      queryOptions({\n        \
         queryKey: [\"users\", \"list\", query ?? {}] as const,\n        \
         queryFn: ({ signal }) => api.users.list(query, { signal }),\n      }),\n"
    ));
    assert!(queries.contains(
        "    getOne: (id: string) =>\n      queryOptions({\n        \
         queryKey: [\"users\", \"getOne\", id] as const,"
    ));
    assert!(queries.contains(
        "    update: (options?: RequestOptions) =>\n      mutationOptions({\n        \
         mutationKey: [\"users\", \"update\"] as const,\n        \
         mutationFn: (variables: { id: string; body: UpdateUserDto }) =>\n          \
         api.users.update(variables.id, variables.body, options),\n      }),\n"
    ));
    assert!(queries.contains(
        "        mutationFn: (body: CredentialsDto) =>\n          api.auth.login(body, options),\n"
    ));
    assert!(queries.contains("        mutationFn: () =>\n          api.auth.resend(options),\n"));
}

