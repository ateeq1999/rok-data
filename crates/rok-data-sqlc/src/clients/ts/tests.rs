use std::path::{Path, PathBuf};

use serde_json::json;

use super::*;

/// The monorepo template's api App's document, read.
fn monorepo() -> Document {
    let text = rok_templates::catalog::files("monorepo")
        .and_then(|files| {
            files
                .iter()
                .find(|file| file.path == "apps/api/openapi.json")
        })
        .map(|file| String::from_utf8_lossy(file.bytes).into_owned())
        .unwrap_or_else(|| panic!("the monorepo template ships no apps/api/openapi.json"));
    Document::parse(&text).unwrap_or_else(|err| panic!("{err}"))
}

fn emitted(document: &Document) -> Vec<(PathBuf, String)> {
    emit(document).unwrap_or_else(|err| panic!("{err}"))
}

fn file<'a>(files: &'a [(PathBuf, String)], path: &str) -> &'a str {
    files
        .iter()
        .find(|(at, _)| at == Path::new(path))
        .map(|(_, text)| text.as_str())
        .unwrap_or_else(|| panic!("no {path}"))
}

#[test]
fn every_file_carries_the_generated_marker() {
    let files = emitted(&monorepo());
    let paths: Vec<&Path> = files.iter().map(|(path, _)| path.as_path()).collect();
    assert_eq!(
        paths,
        [
            "README.md",
            "src/calls.ts",
            "src/index.ts",
            "src/queries.ts",
            "src/runtime.ts",
            "src/types.ts"
        ]
        .map(Path::new)
    );
    for (path, text) in &files {
        let first = text.lines().next().unwrap_or("");
        assert!(
            first.contains("@generated by rok-data-sqlc"),
            "{} lacks the marker: {first}",
            path.display()
        );
    }
}

/// Each operation is a typed call: path parameters, then the body, then
/// the query, then the options; a public one sends no token.
#[test]
fn calls_are_typed_per_operation() {
    let files = emitted(&monorepo());
    let calls = file(&files, "src/calls.ts");
    assert!(calls.contains(
        "    login: (\n      body: CredentialsDto,\n      options?: RequestOptions\n    ) =>\n      \
         request<LoginResponse>(\n        {\n          method: \"POST\",\n          \
         path: \"/api/v1/auth/login\",\n          json: body,\n          secured: false,\n          \
         response: \"json\",\n        },\n        options\n      ),\n"
    ));
    assert!(calls.contains(
        "    update: (\n      id: string,\n      body: UpdateUserDto,\n      options?: RequestOptions\n    ) =>"
    ));
    assert!(calls.contains("path: `/api/v1/users/${encodeURIComponent(String(id))}`"));
    assert!(calls.contains(
        "    list: (\n      query?: UsersListQuery,\n      options?: RequestOptions\n    ) =>\n      \
         request<PaginatedResponse_UserResponse>("
    ));
    // Raw bytes in, raw bytes out, nothing at all.
    assert!(calls.contains("      body: Blob,\n      query?: MediaUploadQuery,"));
    assert!(calls.contains("blob: body,"));
    assert!(calls.contains("request<Blob>("));
    assert!(calls.contains("request<void>("));
    // Two `verify`s of `auth`, told apart by where their paths part.
    assert!(calls.contains("    verify2fa: (\n"));
    assert!(calls.contains("    verifyEmail: (\n"));
    assert!(calls.contains("  apiKeys: {\n"));
}

