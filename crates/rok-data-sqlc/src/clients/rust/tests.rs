use std::path::{Path, PathBuf};

use serde_json::json;

use super::*;

/// The monorepo template's api App's document, read.
fn monorepo() -> Document {
    let text = rok_templates::catalog::files("monorepo")
        .and_then(|files| {
            files
                .iter()
                .find(|file| file.path == "apps/api/openapi.json")
        })
        .map(|file| String::from_utf8_lossy(file.bytes).into_owned())
        .unwrap_or_else(|| panic!("the monorepo template ships no apps/api/openapi.json"));
    Document::parse(&text).unwrap_or_else(|err| panic!("{err}"))
}

fn emitted(document: &Document) -> Vec<(PathBuf, String)> {
    emit(document).unwrap_or_else(|err| panic!("{err}"))
}

fn file<'a>(files: &'a [(PathBuf, String)], path: &str) -> &'a str {
    files
        .iter()
        .find(|(at, _)| at == Path::new(path))
        .map(|(_, text)| text.as_str())
        .unwrap_or_else(|| panic!("no {path}"))
}

/// A document of `paths` and `schemas`, read.
fn parsed(paths: serde_json::Value, schemas: serde_json::Value) -> Document {
    let json = json!({
        "openapi": "3.1.0", "info": {}, "paths": paths,
        "components": {"schemas": schemas},
    })
    .to_string();
    Document::parse(&json).unwrap_or_else(|err| panic!("{err}"))
}

#[test]
fn every_file_carries_the_generated_marker() {
    let files = emitted(&monorepo());
    let paths: Vec<&Path> = files.iter().map(|(path, _)| path.as_path()).collect();
    assert_eq!(
        paths,
        [
            "README.md",
            "src/calls.rs",
            "src/lib.rs",
            "src/runtime.rs",
            "src/types.rs"
        ]
        .map(Path::new)
    );
    for (path, text) in &files {
        let first = text.lines().next().unwrap_or("");
        assert!(
            first.contains("@generated by rok-data-sqlc"),
            "{} lacks the marker: {first}",
            path.display()
        );
    }
}

/// Each operation is a typed `async fn` of its tag's group: path
/// parameters, then the body, then the query.
#[test]
fn calls_are_typed_per_operation() {
    let files = emitted(&monorepo());
    let calls = file(&files, "src/calls.rs");
    assert!(calls.contains(
        "    pub fn users(&self) -> Users<'_> {\n        Users { client: self }\n    }\n"
    ));
    assert!(calls.contains(
        "    pub async fn login(\n        &self,\n        body: &types::CredentialsDto,\n    \
         ) -> Result<types::LoginResponse, ApiError> {\n        \
         let path = \"/api/v1/auth/login\";\n        \
         let call = self.client.call(Method::POST, path, false)?;\n        \
         call.json(body).json_answer().await\n    }\n"
    ));
    // A path parameter is encoded into its place; the call sends the token.
    assert!(calls.contains(
        "        let id = crate::segment(id);\n        \
         let path = format!(\"/api/v1/users/{id}\");\n        \
         let call = self.client.call(Method::PATCH, &path, true)?;\n"
    ));
    assert!(calls.contains("        id: &str,\n        body: &types::UpdateUserDto,\n"));
    assert!(calls.contains(
        "    pub async fn list(\n        &self,\n        query: &types::UsersListQuery,\n    \
         ) -> Result<types::PaginatedResponseUserResponse, ApiError> {"
    ));
    // Raw bytes in, raw bytes out, nothing at all.
    assert!(calls.contains(
        "        body: impl Into<reqwest::Body>,\n        query: &types::MediaUploadQuery,\n"
    ));
    assert!(calls.contains("call.bytes(body).query(query).json_answer().await"));
    assert!(calls.contains("-> Result<Vec<u8>, ApiError> {"));
    assert!(calls.contains("    pub async fn liveness(&self) -> Result<(), ApiError> {"));
    // Two `verify`s of `auth`, told apart by where their paths part.
    assert!(calls.contains("    pub async fn verify2fa(\n"));
    assert!(calls.contains("    pub async fn verify_email(\n"));
    assert!(calls.contains("    pub fn api_keys(&self) -> ApiKeys<'_> {\n"));
}

/// The types follow the schemas: a request's property that may be left
/// out or `null` keeps the two apart, an answer's does not; an inline
/// object shaped like a schema is that schema.
#[test]
fn types_follow_the_schemas() {
    let files = emitted(&monorepo());
    let types = file(&files, "src/types.rs");
    assert!(types.contains(
        "pub enum Role {\n    /// `user`.\n    #[serde(rename = \"user\")]\n    User,\n"
    ));
    assert!(types.contains("            Role::Admin => \"admin\",\n"));
    assert!(types.contains(
        "#[derive(Debug, Clone, Default, PartialEq, Serialize, Deserialize)]\npub struct UpdateUserDto {"
    ));
    assert!(types.contains(
        "    #[serde(default, skip_serializing_if = \"Option::is_none\")]\n    \
         #[serde(deserialize_with = \"crate::nullable\")]\n    \
         pub role: Option<Option<Role>>,\n"
    ));
    assert!(types.contains("    pub avatar_url: Option<String>,\n"));
    assert!(types.contains("    pub items: Vec<UserResponse>,\n"));
    // `allOf` merges the key's properties with the secret.
    let created = types
        .split("pub struct CreatedApiKeyResponse {")
        .nth(1)
        .and_then(|rest| rest.split("\n}\n").next())
        .unwrap_or_default();
    assert!(
        created.contains("    pub key_prefix: String,\n"),
        "{created}"
    );
    assert!(created.ends_with("    pub key: String,"), "{created}");
    // `oneOf`: either shape, untagged.
    assert!(types.contains(
        "#[serde(untagged)]\n#[allow(clippy::large_enum_variant)]\npub enum LoginResponse {\n"
    ));
    assert!(types.contains("    TokenResponse(TokenResponse),\n"));
    assert!(types.contains("    PendingToken(LoginResponsePendingToken),\n"));
    assert!(types.contains("pub struct UsersListQuery {"));
    assert!(types.contains("    pub sort: Option<UserSort>,\n"));
}

/// A query parameter the query encoder cannot send (an array, an object)
/// is reported, not emitted to fail at run time.
#[test]
fn a_query_parameter_of_many_values_is_refused() {
    let document = parsed(
        json!({"/t": {"get": {"operationId": "list", "tags": ["t"],
            "parameters": [{"name": "ids", "in": "query",
                "schema": {"type": "array", "items": {"type": "string"}}}],
            "responses": {"204": {"description": ""}}}}}),
        json!({}),
    );
    assert_eq!(
        emit(&document).err().map(|err| err.to_string()).as_deref(),
        Some(
            "`GET /t`: the query parameter `ids` is an array or an object, which the Rust \
             client does not send"
        )
    );
}

/// A schema named like one of the crate root's exports cannot be
/// re-exported beside it, and a tag cannot take a method of `Client`.
#[test]
fn names_the_crate_has_are_refused() {
    let document = parsed(json!({}), json!({"Client": {"type": "string"}}));
    assert_eq!(
        emit(&document).err().map(|err| err.to_string()).as_deref(),
        Some(
            "the schema `Client` takes the name of the client's `Client`; rename the Rust \
             type (or its `#[schema(as = ...)]`)"
        )
    );
    let document = parsed(
        json!({"/t": {"get": {"operationId": "t", "tags": ["token"],
            "responses": {"204": {"description": ""}}}}}),
        json!({}),
    );
    assert_eq!(
        emit(&document).err().map(|err| err.to_string()).as_deref(),
        Some("the tag `token` takes the name of the client's `token`; rename the tag")
    );
}

/// The document generated features serve (`tests/api-app`), read: its
/// versioned `documents` take `If-Match` on `PATCH`.
fn api_app() -> Document {
    let path = concat!(
        env!("CARGO_MANIFEST_DIR"),
        "/tests/api-app/tests/expected/openapi.json"
    );
    let text = std::fs::read_to_string(path).unwrap_or_else(|err| panic!("{path}: {err}"));
    Document::parse(&text).unwrap_or_else(|err| panic!("{err}"))
}

/// A header parameter is an argument after the query, named after the
/// header in `snake_case` and documented: a versioned row's update takes
/// the version for `If-Match`.
#[test]
fn header_parameters_are_arguments_after_the_query() {
    let files = emitted(&api_app());
    let calls = file(&files, "src/calls.rs");
    assert!(
        calls.contains(
            "    /// Sends the session's token.\n    ///\n    \
             /// `if_match` is sent as `If-Match`: the row's `ETag`.\n    \
             pub async fn update(\n        &self,\n        id: &str,\n        \
             body: &types::UpdateDocumentDto,\n        if_match: &str,\n    \
             ) -> Result<types::DocumentResponse, ApiError> {\n        \
             let id = crate::segment(id);\n        \
             let path = format!(\"/api/v1/documents/{id}\");\n        \
             let call = self.client.call(Method::PATCH, &path, true)?;\n        \
             call.json(body)\n            .header(\"If-Match\", if_match)\n            \
             .json_answer()\n            .await\n    }\n"
        ),
        "{calls}"
    );
    let runtime = file(&files, "src/runtime.rs");
    assert!(runtime.contains("    pub fn header(mut self, name: &str, value: &str) -> Call {"));
}

/// An optional header is an `Option`, sent only when it is `Some`.
#[test]
fn an_optional_header_is_an_option() {
    let document = parsed(
        json!({"/things": {"get": {
            "operationId": "list", "tags": ["things"],
            "parameters": [{"name": "X-Trace-Id", "in": "header", "schema": {"type": "string"}}],
            "responses": {"204": {"description": ""}},
        }}}),
        json!({}),
    );
    let files = emitted(&document);
    let calls = file(&files, "src/calls.rs");
    assert!(
        calls.contains(
            "    pub async fn list(&self, x_trace_id: Option<&str>) -> Result<(), ApiError> {\n        \
             let path = \"/things\";\n        \
             let call = self.client.call(Method::GET, path, false)?;\n        \
             call.optional_header(\"X-Trace-Id\", x_trace_id)\n            \
             .empty_answer()\n            .await\n    }\n"
        ),
        "{calls}"
    );
}
