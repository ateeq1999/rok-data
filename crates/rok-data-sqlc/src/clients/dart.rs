/// The client's `README.md`.
fn readme(operations: &[super::ts::Named<'_>]) -> String {
    let example = operations
        .first()
        .map_or_else(String::new, |named| {
            format!(
                "\n```dart\nimport 'package:{PACKAGE}/{PACKAGE}.dart';\n\n\
                 final api = ApiClient(\n  baseUrl: 'https://api.example.com',\n  \
                 session: Session(token: () => store.token, onExpired: (_) => store.signOut()),\n);\n\
                 final result = await api.{}.{}(/* ... */);\n```\n",
                names::member_name(&named.group),
                names::member_name(&named.name)
            )
        });
    format!(
        "\n# The API's Dart client\n\n\
         Generated from the API's `openapi.json` by `rok gen` (and `rok init`); never \
         edit these files by hand — change the API, then `rok gen` re-exports the \
         document and regenerates them. An App depends on it by path:\n\n\
         ```yaml\ndependencies:\n  {PACKAGE}:\n    path: ../../clients/dart\n```\n\n\
         - `ApiClient(baseUrl: ..., session: ...)`: one per App. `api.<tag>.<operation>(...)` \
         is one typed method per operation: path parameters first, then the body, then the \
         query by name, then `options` (`RequestOptions`).\n\
         - Every model has `fromJson` and `toJson`; a `oneOf` is a sealed class to `switch` \
         over. A request's optional, nullable field takes `Nullable(value)`: \
         `Nullable(null)` clears it, leaving it out keeps it.\n\
         - `Session` gives the bearer token the secured operations send; a `401` to one \
         of them calls its `expired` (unless the call says `keepSession`).\n\
         - `ApiException` (`status`, `code`, `message`, and a `422`'s `details` of \
         `FieldIssue`s by field) is what every failure throws.\n{example}"
    )
}

