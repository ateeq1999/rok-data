//! The Dart Client (workspace ADR 0027): `clients/dart`, a pub package
//! emitted from the [`Document`] for a Flutter (or any Dart) App. Its
//! files:
//!
//! - `lib/src/runtime.dart` — `ApiException` (status, code, message and
//!   the `422`'s `FieldIssue`s by field), `Session` (where the bearer
//!   token comes from, and what a rejected one ends), `RequestOptions`,
//!   `Bytes`, `Nullable` and the transport every call goes through. The
//!   same text for every document.
//! - `lib/src/models.dart` — a class per object schema (with `fromJson`
//!   and `toJson`), an enum per string enum, a sealed class per `oneOf`
//!   of objects.
//! - `lib/src/client.dart` — `ApiClient`, a getter per tag and a typed
//!   method per operation: `api.users.update(id, body)`.
//! - `lib/api_client.dart` (the library), `pubspec.yaml`,
//!   `analysis_options.yaml`, `.gitignore` and `README.md`.
//!
//! What the Dart client cannot type is refused, naming it and where: an
//! object with both properties and `additionalProperties`, a `oneOf` of
//! non-objects, a query parameter that is not a scalar... Every file
//! carries the engine's generated marker, so the writer's rules apply as
//! to the other Clients (workspace ADR 0005).

