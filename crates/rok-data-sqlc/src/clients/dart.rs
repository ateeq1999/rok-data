/// The first line of every emitted Dart file.
const HEADER: &str = "// @generated by rok-data-sqlc from openapi.json. Do not edit by hand.\n";

/// The first line of every emitted YAML file and of `.gitignore`.
const HASH_HEADER: &str = "# @generated by rok-data-sqlc from openapi.json. Do not edit by hand.\n";

/// The first line of the emitted `README.md`.
const MARKDOWN_HEADER: &str =
    "<!-- @generated by rok-data-sqlc from openapi.json. Do not edit by hand. -->\n";

/// The runtime every call goes through: the same for every document.
const RUNTIME: &str = include_str!("dart/runtime.dart");

/// The package's name, which an App's `pubspec.yaml` depends on.
pub const PACKAGE: &str = "api_client";

/// Why the client cannot be emitted from a document the reader accepted.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Error(String);

impl std::fmt::Display for Error {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str(&self.0)
    }
}

impl std::error::Error for Error {}

/// The client's files for `document`, each its path relative to the
/// client's directory and its text.
///
/// # Errors
///
/// When the document holds a construct the Dart client cannot type, or
/// a name the document asks for is one the client takes already.
pub fn emit(document: &Document) -> Result<Vec<(PathBuf, String)>, Error> {
    let operations = name_operations(&document.operations);
    let groups: BTreeSet<String> = operations
        .iter()
        .map(|named| client::group_class(&named.group))
        .collect();
    let mut models = models::Models::of(document, groups)?;
    let client = client::file(&operations, &mut models)?;
    let models = render::file(&models.finish());
    let mut files = vec![
        (
            PathBuf::from("README.md"),
            format!("{MARKDOWN_HEADER}{}", readme(&operations)),
        ),
        (
            PathBuf::from(".gitignore"),
            format!("{HASH_HEADER}.dart_tool/\npubspec.lock\n"),
        ),
        (
            PathBuf::from("pubspec.yaml"),
            format!("{HASH_HEADER}{PUBSPEC}"),
        ),
        (
            PathBuf::from("analysis_options.yaml"),
            format!("{HASH_HEADER}{ANALYSIS_OPTIONS}"),
        ),
        (
            PathBuf::from("lib/api_client.dart"),
            format!("{HEADER}{LIBRARY}"),
        ),
        (
            PathBuf::from("lib/src/runtime.dart"),
            format!("{HEADER}\n{RUNTIME}"),
        ),
        (
            PathBuf::from("lib/src/models.dart"),
            format!("{HEADER}{models}"),
        ),
        (
            PathBuf::from("lib/src/client.dart"),
            format!("{HEADER}{client}"),
        ),
    ];
    files.sort_by(|a, b| a.0.cmp(&b.0));
    Ok(files)
}

