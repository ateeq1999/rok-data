/// The text of `path` under `dir`, or the error naming it.
fn read(dir: &Path, path: &str) -> Result<String> {
    fs::read_to_string(dir.join(path)).with_context(|| format!("no `{path}` in the scaffold"))
}

/// A Monorepo scaffold names every App after the project (its directory)
/// and the org: the api and desktop crates, and their Rust paths, the web
/// package, the mobile package, its Android and iOS ids, its display name
/// and its deep-link scheme (workspace ADR 0027).
#[test]
fn a_monorepo_scaffold_names_every_app_after_the_project() -> Result<()> {
    let parent = tempfile::tempdir()?;
    let dir = parent.path().join("my-shop");
    let scaffolded = init_template(&dir, "monorepo", Some("com.acme"))?;
    assert_eq!(scaffolded.api_package.as_deref(), Some("my-shop-api"));
    assert!(read(&dir, "apps/api/Cargo.toml")?.contains("name = \"my-shop-api\"\n"));
    assert!(read(&dir, "apps/api/src/main.rs")?.contains("my_shop_api::"));
    assert!(read(&dir, "rok.toml")?.contains("\"-p\", \"my-shop-api\""));
    assert!(read(&dir, "apps/desktop/Cargo.toml")?.contains("name = \"my-shop-desktop\"\n"));
    assert!(read(&dir, "apps/desktop/src/main.rs")?.contains("my_shop_desktop::app::App"));
    assert!(read(&dir, "apps/web/package.json")?.contains("\"name\": \"my-shop-web\","));
    assert!(read(&dir, "apps/mobile/pubspec.yaml")?.starts_with("name: my_shop_mobile\n"));
    let gradle = read(&dir, "apps/mobile/android/app/build.gradle.kts")?;
    assert!(
        gradle.contains("applicationId = \"com.acme.my_shop\""),
        "{gradle}"
    );
    let activity = "apps/mobile/android/app/src/main/kotlin/com/acme/my_shop/MainActivity.kt";
    assert!(read(&dir, activity)?.starts_with("package com.acme.my_shop\n"));
    let plist = read(&dir, "apps/mobile/ios/Runner/Info.plist")?;
    assert!(plist.contains("<string>My Shop</string>"), "{plist}");
    assert!(plist.contains("<string>myshop</string>"), "{plist}");
    let pbxproj = read(&dir, "apps/mobile/ios/Runner.xcodeproj/project.pbxproj")?;
    assert!(pbxproj.contains("PRODUCT_BUNDLE_IDENTIFIER = com.acme.myShop;"));
    // The root lock names the renamed packages.
    let lock = read(&dir, "Cargo.lock")?;
    assert!(lock.contains("name = \"my-shop-api\"") && lock.contains("name = \"my-shop-desktop\""));
    assert!(!lock.contains("name = \"axum-api\""));
    Ok(())
}

