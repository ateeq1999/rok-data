/// An org or a project name that would break an identifier is rejected
/// before anything is written.
#[test]
fn a_name_that_breaks_an_identifier_is_rejected_before_writing() -> Result<()> {
    let parent = tempfile::tempdir()?;
    let dir = parent.path().join("shop");
    let err = init_template(&dir, "monorepo", Some("Acme")).err();
    assert!(
        err.is_some_and(|err| err
            .to_string()
            .contains("`--org Acme` is not a reverse-domain name")),
        "an invalid org was accepted"
    );
    assert!(!dir.exists(), "a rejected org wrote files");
    let dir = parent.path().join("2shop");
    let err = init_template(&dir, "monorepo", None).err();
    assert!(
        err.is_some_and(|err| err.to_string().contains("starts with a digit")),
        "a project name starting with a digit was accepted"
    );
    assert!(!dir.exists(), "a rejected project name wrote files");
    Ok(())
}

