//! The files at the root of `api.output`: `generated.rs`, which declares
//! every feature and mounts them, and `README.md`, which maps the files.
//!
//! The framework decides what `generated.rs` holds ([`Framework::generated`]);
//! this module holds what both share: the module declarations, the
//! re-exports, and the README.

use super::feature::Feature;
use super::framework::Framework;

/// The generated marker of a Markdown file, which the writer recognizes as
/// it does [`HEADER`](crate::generator::HEADER).
const MARKDOWN_HEADER: &str = "<!-- @generated by rok-data-sqlc. Do not edit by hand. Regenerated by `rok sqlc generate`. -->\n";

/// The module declarations of every feature, sorted by name as rustfmt
/// sorts them.
pub fn modules(features: &[Feature<'_>]) -> String {
    let mut modules: Vec<&str> = features.iter().map(Feature::module).collect();
    modules.sort_unstable();
    let mut output = String::new();
    for module in modules {
        output.push_str(&format!(
            "\n#[path = \"{module}/mod.rs\"]\npub mod {module};"
        ));
    }
    if !features.is_empty() {
        output.push('\n');
    }
    output
}

/// The re-exports of the responses the features' relationship routes answer
/// with: a feature names another's response only through these, never its
/// module.
pub fn related(features: &[Feature<'_>]) -> String {
    let mut related: Vec<(&str, String)> = features
        .iter()
        .flat_map(|feature| {
            feature
                .relations
                .iter()
                .filter(|relation| relation.target.module_name != feature.module())
                .map(|relation| (relation.target.module_name.as_str(), relation.response()))
        })
        .collect();
    related.sort();
    related.dedup();
    let mut output = String::new();
    if !related.is_empty() {
        output.push_str("\n// The responses other features' relationship routes answer with.\n");
        for (module, response) in related {
            output.push_str(&format!("pub use {module}::dto::{response};\n"));
        }
    }
    output
}

/// Renders `README.md`.
pub fn render_readme(features: &[Feature<'_>], framework: Framework) -> String {
    let mut output = format!(
        "{MARKDOWN_HEADER}
# API features

`rok sqlc generate` generates one folder per table here, from the schema and the
`[api]` section of `rok-data-sqlc.toml`. Every file starting with
`// @generated by rok-data-sqlc` is rewritten on each run, and removed once its
table is gone: don't edit it. `service.rs` starts with
`// Scaffolded once by rok-data-sqlc`: it is written once, then it is yours, and
rok-data-sqlc never touches it again.

| File | Owner | Holds |
|---|---|---|
| `generated.rs` | generated | declares the features; {} |
| `<feature>/mod.rs` | generated | the module list; re-exports `routes`, the service and its trait |
| `<feature>/routes.rs` | generated | URL to handler |
| `<feature>/handlers.rs` | generated | parse, call one service method, answer |
| `<feature>/dto.rs` | generated | request and response bodies |
| `<feature>/model.rs` | generated | the rows and typed ids, from `db` |
| `<feature>/repo.rs` | generated | the table's `db` functions |
| `<feature>/service_api.rs` | generated | the service trait, a default per endpoint |
| `<feature>/service.rs` | **yours** | the service and your overrides: business rules go here |

## Features
",
        framework.root_summary()
    );
    if features.is_empty() {
        output.push_str("\nNone: every table is excluded.\n");
    } else {
        output.push_str("\n| Feature | URL | Endpoints |\n|---|---|---|\n");
    }
    for feature in features {
        let endpoints: Vec<String> = feature
            .endpoints
            .iter()
            .map(|endpoint| format!("`{}`", endpoint.name()))
            .collect();
        output.push_str(&format!(
            "| `{}` | `{}` | {} |\n",
            feature.module(),
            feature.url,
            endpoints.join(", ")
        ));
    }
    output
}
